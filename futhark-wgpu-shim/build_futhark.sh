#!/bin/bash
# The link step (docs/PLAN_futhark_wgpu_host.md §5, artefact 5): Futhark's
# generated webgpu C, compiled with plain `cc` against the generated header,
# linked against this crate's static library.
#
#   build_futhark.sh [--dawn] <generated.c> <output-executable> [more.c ...]
#
#   --dawn      build the runtime's USE_DAWN wait path (futures and
#               wgpuInstanceWaitAny) instead of the default one
#               (AllowSpontaneous callbacks and emscripten_sleep).
#   more.c      further C files to compile in (a driver for a --library
#               build).
#
# Steps, each one a hard stop on failure:
#   1. cargo build --release of the shim (the header is generated by it);
#   2. the generated header must be byte-identical to the committed
#      include/webgpu/webgpu.h (acceptance criterion 4);
#   3. tools/port_futhark_c.py ports the embedded WGSL (its audit goes to
#      <output>.port.log);
#   4. cc compiles the C;
#   5. every wgpu*/emscripten* symbol the objects leave undefined must be
#      exported by the shim AND listed in surface/wgpu_functions.txt (plus
#      emscripten_sleep): the surface cannot quietly grow (criterion 3);
#   6. cc links.
#
# Each step's wall time (seconds) is written to <output>.stages.tsv: port, cc, check (the surface check) and link,
# one line each, for the caller's per-stage timing.
#
# Builds run under /private/tmp/claude-501/locks/cargo (mkdir lock), held only
# while cargo or cc runs. A caller that already holds that lock (a test run
# under a lock wrapper reaches this script through the futhark_wgpu_host test)
# says so with CARGO_LOCK_HELD=<the lock's path>; the script then does not take
# it again, which would wait on its own caller until the test's 900 s guard
# fired (the futhark_wgpu_host failure of 2026-10-27).
set -euo pipefail
here=$(cd "$(dirname "$0")" && pwd)
dawn=()
if [ "${1:-}" = "--dawn" ]; then
  dawn=(-DUSE_DAWN)
  shift
fi
if [ $# -lt 2 ]; then
  sed -n '2,25p' "$0" >&2
  exit 2
fi
src=$1
exe=$2
shift 2
extra=("$@")

lock=/private/tmp/claude-501/locks/cargo
if [ "${CARGO_LOCK_HELD:-}" = "$lock" ]; then
  take_lock() { :; }
  drop_lock() { :; }
else
  take_lock() { until mkdir "$lock" 2>/dev/null; do sleep 2; done; trap 'rmdir "$lock" 2>/dev/null || true' EXIT; }
  drop_lock() { rmdir "$lock"; trap - EXIT; }
fi

work="$exe.build"
mkdir -p "$work"
now() { perl -MTime::HiRes=time -e 'printf "%.6f", time'; }
stages="$exe.stages.tsv"
: >"$stages"
since() { perl -e 'printf "%s\t%.6f\n", $ARGV[0], $ARGV[2] - $ARGV[1]' "$1" "$2" "$(now)" >>"$stages"; }

# 1. the shim, and where its generated header is. With FUTHARK_SHIM_PREBUILT=<dir> (written once by
# `prebuild_shim.sh <dir>`), the library and the generated header are read from <dir>: no cargo runs and no lock is
# taken, so a running evolution never waits on a build (the pathfinder pilot of 2026-10-27 stalled 14 minutes on a
# lock another job had left behind).
if [ -n "${FUTHARK_SHIM_PREBUILT:-}" ]; then
  take_lock() { :; }
  drop_lock() { :; }
  out_dir=$FUTHARK_SHIM_PREBUILT
  lib=$FUTHARK_SHIM_PREBUILT/libfuthark_wgpu_shim.a
  if [ ! -f "$lib" ] || [ ! -f "$out_dir/include/webgpu/webgpu.h" ]; then
    echo "build_futhark.sh: FUTHARK_SHIM_PREBUILT=$out_dir holds no libfuthark_wgpu_shim.a and include/webgpu/webgpu.h (run prebuild_shim.sh)" >&2
    exit 1
  fi
else
take_lock
(cd "$here" && RUSTFLAGS="-D warnings" cargo build --release --message-format=json-render-diagnostics) >"$work/cargo.json"
drop_lock
# Both paths come from cargo's own messages, so a caller's CARGO_TARGET_DIR
# (a cargo test inherits one) is honoured rather than guessed past.
read -r out_dir lib < <(python3 -I -c '
import json, sys
out_dir = lib = ""
for line in open(sys.argv[1]):
    try:
        m = json.loads(line)
    except ValueError:
        continue
    if "futhark-wgpu-shim" not in m.get("package_id", ""):
        continue
    if m.get("reason") == "build-script-executed":
        out_dir = m["out_dir"]
    if m.get("reason") == "compiler-artifact":
        for f in m.get("filenames", []):
            if f.endswith(".a"):
                lib = f
print(out_dir, lib)
' "$work/cargo.json")
if [ -z "${out_dir:-}" ] || [ -z "${lib:-}" ]; then
  echo "build_futhark.sh: cargo reported no header directory or static library for the shim" >&2
  exit 1
fi
fi

# 2. the generated header is the committed one.
if ! cmp -s "$out_dir/include/webgpu/webgpu.h" "$here/include/webgpu/webgpu.h"; then
  echo "build_futhark.sh: include/webgpu/webgpu.h is not the generated header; after a deliberate change to the surface, refresh it with FUTHARK_WGPU_SHIM_BLESS=1 cargo build --release" >&2
  exit 1
fi

# 3. the WGSL port.
ported="$work/$(basename "${src%.c}").ported.c"
t=$(now)
python3 -I "$here/tools/port_futhark_c.py" "$src" "$ported" >"$exe.port.log"
since port "$t"

# 4. compile.
objs=()
take_lock
t=$(now)
for c in "$ported" ${extra[@]+"${extra[@]}"}; do
  o="$work/$(basename "${c%.c}").o"
  cc -O2 ${dawn[@]+"${dawn[@]}"} -I"$out_dir/include" -I"$here/include" -I"$(dirname "$src")" -c "$c" -o "$o"
  objs+=("$o")
done
drop_lock
since cc "$t"

# 5. the surface check.
t=$(now)
/usr/bin/nm -u "${objs[@]}" 2>/dev/null | grep -oE '_(wgpu[A-Za-z0-9]+|emscripten_[a-z_]+)$' | sed 's/^_//' | sort -u >"$work/undefined.txt"
/usr/bin/nm -gU "$lib" 2>/dev/null | grep -oE ' T _(wgpu[A-Za-z0-9]+|emscripten_[a-z_]+)$' | sed 's/^ T _//' | sort -u >"$work/exported.txt"
{ cat "$here/surface/wgpu_functions.txt"; echo emscripten_sleep; } | sort -u >"$work/surface.txt"
missing=$(comm -23 "$work/undefined.txt" "$work/exported.txt")
outside=$(comm -23 "$work/undefined.txt" "$work/surface.txt")
if [ -n "$missing" ] || [ -n "$outside" ]; then
  echo "build_futhark.sh: the generated C needs symbols outside the shim's surface:" >&2
  [ -n "$missing" ] && echo "  not exported by the shim: $missing" >&2
  [ -n "$outside" ] && echo "  not in surface/wgpu_functions.txt: $outside" >&2
  exit 1
fi
since check "$t"

# 6. link.
take_lock
t=$(now)
cc -o "$exe" "${objs[@]}" "$lib" \
  -framework QuartzCore -framework CoreGraphics -liconv -framework Metal \
  -framework Foundation -framework CoreFoundation -lobjc -lm
drop_lock
since link "$t"
echo "built $exe ($(wc -l <"$work/undefined.txt" | tr -d ' ') shim symbols used; port: $(tail -1 "$exe.port.log"))"
