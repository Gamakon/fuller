//! The Futhark kingdom's **static cost**: what a program costs, as a
//! polynomial in the dimension roles.
//!
//! This is the fitness's cost half, and it is deliberately *not* a
//! measurement and *not* wall-clock time:
//!
//! * **Not wall-clock.** C-backend time does not transfer to the GPU:
//!   fusion and traversal counts matter differently there, and a search
//!   that optimises for the wrong machine is worse than no search. This
//!   model is the cheap *filter*; the cost that decides is measured on the
//!   GPU, in phylu's `futhark_eval::gpu` (moved in plan 5b).
//! * **Not a measurement.** The numbers come from the kingdom's own table
//!   (`kingdoms/futhark/costs.tsv`, generated), so they are a
//!   *model* that the table and the generator's witness tests keep honest,
//!   not a number that drifts with the machine.
//!
//! # What is charged
//!
//! Three things, all in elements:
//!
//! * **traffic** — elements read and written;
//! * **allocations** — elements of fresh memory;
//! * **serial depth** — the length of the longest reduction, which is what
//!   limits a GPU's parallelism.
//!
//! # The matmul is charged the TILED traffic
//!
//! Futhark 0.28.1 has no `matmul` intrinsic, so the kingdom brings its own,
//! and that helper is a nested map/reduce. On the GPU that shape is exactly
//! what the compiler's own tiler recognises: `gpuPipeline` runs `tileLoops`
//! (`Futhark/Optimise/TileLoops.hs`), and the block+register tiler
//! (`Futhark/Optimise/BlkRegTiling.hs`) names SGEMM as one of its target
//! patterns.
//!
//! So the `matmul` row is charged the traffic the **tiled** version
//! achieves — each operand element read once — and not the traffic the naive
//! nested map/reduce actually costs. The tiling is the compiler's business;
//! a cost model that charged for it would rank a program against a machine
//! it will never run on.
//!
//! # Fusion
//!
//! An **elementwise** row (`map_rows`, `map2_rows`) *absorbs* its input: a
//! chain of maps costs one traversal, not one per link. The rule is
//! structural, not a rewrite: a node whose only consumer is elementwise is
//! not materialised, so neither its write nor its allocation is charged, and
//! the consumer does not read it separately.
//!
//! The rule reaches further than a chain of maps: it absorbs *any* producer
//! into an elementwise consumer, a product or a transpose included, because
//! that is what Futhark's own SOAC fusion does — `map f (matmul A B)` is one
//! loop nest to the compiler, not two.
//!
//! A terminal is never absorbed — it is the interface's own input, and it
//! is always materialised.

