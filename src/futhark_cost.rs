//! The Futhark kingdom's **static cost**: what a program costs, from per-row formulas over its arguments' properties.
//!
//! This is the fitness's cost half, and it is deliberately *not* a
//! measurement and *not* wall-clock time:
//!
//! * **Not wall-clock.** C-backend time does not transfer to the GPU:
//!   fusion and traversal counts matter differently there, and a search
//!   that optimises for the wrong machine is worse than no search. This
//!   model is the cheap *filter*; the cost that decides is measured on the
//!   GPU, in phylu's `futhark_eval::gpu` (moved in plan 5b).
//! * **Not a measurement.** The numbers come from the master's own table
//!   (`kingdoms/futhark/master/6/costs.tsv`, generated), so they are a
//!   *model* that the table and the generator's witness tests keep honest,
//!   not a number that drifts with the machine.
//!
//! # What is charged
//!
//! Three things, all in elements:
//!
//! * **traffic** — elements read and written;
//! * **allocations** — elements of fresh memory;
//! * **serial depth** — the length of the longest reduction, which is what
//!   limits a GPU's parallelism.
//!
//! # The matmul is charged the TILED traffic
//!
//! Futhark 0.28.1 has no `matmul` intrinsic, so the kingdom brings its own,
//! and that helper is a nested map/reduce. On the GPU that shape is exactly
//! what the compiler's own tiler recognises: `gpuPipeline` runs `tileLoops`
//! (`Futhark/Optimise/TileLoops.hs`), and the block+register tiler
//! (`Futhark/Optimise/BlkRegTiling.hs`) names SGEMM as one of its target
//! patterns. So the `matmul` row is charged the traffic the **tiled** version
//! achieves — each operand element read once.
//!
//! # Fusion
//!
//! An **elementwise** row (`map_rows`, `map2_rows`) *absorbs* its input: a
//! chain of maps costs one traversal, not one per link, as Futhark's own SOAC
//! fusion makes it. A root variable (the interface's own input) is always
//! materialised.

use std::collections::BTreeMap;

use crate::futhark_table::Kingdom6;
use crate::geneframe::{DataKind, PropertyExpr, Ty};
use crate::typed_environment::{Decoding, Node as Node6, Substituted, Substitution};

/// A program's cost, evaluated at a set of sizes.
///
/// The three components are compared in order: less traffic wins; if the
/// traffic ties, fewer allocations; if that ties too, the shorter
/// reduction.
#[derive(Debug, Clone, Copy, PartialEq, Eq, PartialOrd, Ord)]
pub struct Score {
    /// The elements read and written.
    pub traffic: u64,
    /// The elements of fresh memory.
    pub alloc: u64,
    /// The longest reduction.
    pub depth: u64,
}

// ---- master 6 (plan section 7, task F3) ---------------------------------------------------------------------------
//
// MASTER 6's STATIC COST: per-row formulas over the ARGUMENTS' PROPERTIES (`kingdoms/futhark/master/6/costs.tsv`,
// generated by `gen_tables.py` with its witness C1-C6), keyed by each symbol's master row. An ADAPTER is a row like any
// other, and its `traffic` (a `fit` the cells it writes and reads, `clampix` its two compares) is charged wherever it
// is in the program: placed by evolution (a node of the tree) or called by a repair (the decoder's
// `Decoder::node_calls`), so selection prefers programs that need no rescue (design 4, the second engine). A node's
// costs count once a trip of every binder above it, its depth once a trip of every loop above it; materialised nodes
// write and allocate, a materialised argument is read by its consumer, an elementwise consumer absorbs its arguments.

/// Master 6's cost table, generated by `gen_tables.py` and committed like the master.
const COSTS6_TSV: &str = include_str!("../kingdoms/futhark/master/6/costs.tsv");

/// The columns of [`COSTS6_TSV`].
const COSTS6_COLUMNS: [&str; 9] = ["kind", "ref", "name", "reads", "write", "alloc", "depth", "absorb", "traffic"];

/// One factor of a master 6 cost formula.
#[derive(Debug, Clone, PartialEq, Eq)]
enum Factor6 {
    /// A property of the row's result (`out.len`, `out.cells`).
    Out(String),
    /// A property of an argument as the node's repairs leave it (`in1.cells`).
    In(usize, String),
}

/// A master 6 cost formula: a sum of products of an integer coefficient and factors.
#[derive(Debug, Clone, PartialEq, Eq, Default)]
pub struct Formula6 {
    terms: Vec<(u128, Vec<Factor6>)>,
}

impl Formula6 {
    /// Parse `0`, or a sum (`+`) of products (`*`) of integers, `out.<p>` and `in<k>.<p>`.
    fn parse(text: &str) -> Result<Formula6, String> {
        let bad = || format!("our software has a bug: futhark_cost: the master 6 cost formula {text:?}");
        if text == "0" {
            return Ok(Formula6::default());
        }
        let mut terms = Vec::new();
        for term in text.split('+') {
            let mut coefficient = 1u128;
            let mut factors = Vec::new();
            for f in term.split('*') {
                if let Ok(c) = f.parse::<u128>() {
                    coefficient = coefficient.checked_mul(c).ok_or_else(bad)?;
                } else if let Some(p) = f.strip_prefix("out.") {
                    factors.push(Factor6::Out(p.to_string()));
                } else if let Some((k, p)) = f.strip_prefix("in").and_then(|r| r.split_once('.')) {
                    factors.push(Factor6::In(k.parse().map_err(|_| bad())?, p.to_string()));
                } else {
                    return Err(bad());
                }
            }
            terms.push((coefficient, factors));
        }
        Ok(Formula6 { terms })
    }

    /// The formula's value, each factor's by `value`.
    fn eval(&self, value: &dyn Fn(&Factor6) -> Result<u128, String>) -> Result<u128, String> {
        let overflow = || "futhark_cost: a master 6 cost overflows u128".to_string();
        let mut total = 0u128;
        for (c, factors) in &self.terms {
            let mut term = *c;
            for f in factors {
                term = term.checked_mul(value(f)?).ok_or_else(overflow)?;
            }
            total = total.checked_add(term).ok_or_else(overflow)?;
        }
        Ok(total)
    }

    /// Whether the formula is the zero formula.
    fn is_zero(&self) -> bool {
        self.terms.is_empty()
    }
}

/// The cost of one master 6 row.
#[derive(Debug, Clone)]
pub struct RowCost6 {
    /// What it reads from each argument that is materialised, in argument order.
    reads: Vec<Formula6>,
    /// What it writes, and allocates, when it is materialised itself.
    write: Formula6,
    alloc: Formula6,
    /// Its serial depth.
    depth: Formula6,
    /// Whether it is elementwise, and so absorbs its arguments.
    absorb: bool,
    /// What it adds each time it runs, materialised or not (an adapter's own work).
    traffic: Formula6,
}

/// Master 6's cost table: each master row's cost by its ref.
#[derive(Debug, Clone)]
pub struct CostTable6 {
    rows: BTreeMap<String, RowCost6>,
}

/// A value's data type and properties: what a cost formula's `in<k>.<p>` or `out.<p>` reads.
pub type Valued6 = (Ty, BTreeMap<String, PropertyExpr>);

impl CostTable6 {
    /// Load the table, and check that every symbol of `k` (by its master row) has a line reading its arguments.
    pub fn load(k: &Kingdom6) -> Result<CostTable6, String> {
        let bug = |what: String| format!("our software has a bug: futhark_cost: master/6/costs.tsv: {what}");
        let mut lines = COSTS6_TSV.lines();
        let header: Vec<&str> = lines.next().unwrap_or("").split('\t').collect();
        if header != COSTS6_COLUMNS {
            return Err(bug(format!("the header is {header:?}, wants {COSTS6_COLUMNS:?}")));
        }
        let mut rows = BTreeMap::new();
        for line in lines.filter(|l| !l.trim().is_empty()) {
            let f: Vec<&str> = line.split('\t').collect();
            if f.len() != COSTS6_COLUMNS.len() || f[0] != "row" {
                return Err(bug(format!("the line {line:?} is not a row's cost")));
            }
            let reads = if f[3].is_empty() { Vec::new() } else { f[3].split(';').map(Formula6::parse).collect::<Result<Vec<_>, _>>()? };
            let cost = RowCost6 { reads, write: Formula6::parse(f[4])?, alloc: Formula6::parse(f[5])?, depth: Formula6::parse(f[6])?, absorb: f[7] == "1", traffic: Formula6::parse(f[8])? };
            if rows.insert(f[1].to_string(), cost).is_some() {
                return Err(bug(format!("the row {} has two lines", f[1])));
            }
        }
        for s in k.symbols() {
            let r = rows.get(&s.alias).ok_or_else(|| bug(format!("the row {} ({}) has no cost", s.alias, s.symbol_name)))?;
            let n = k.inputs(s.symbol as crate::kingdom_contract::SymbolId).len();
            if r.reads.len() != n {
                return Err(bug(format!("{} reads {} arguments and takes {n}", s.symbol_name, r.reads.len())));
            }
        }
        Ok(CostTable6 { rows })
    }

    /// The cost of a master row, by its ref.
    pub fn row(&self, reference: &str) -> Result<&RowCost6, String> {
        self.rows.get(reference).ok_or_else(|| format!("our software has a bug: futhark_cost: the row {reference} has no cost"))
    }

    /// The `traffic` of a row run once on arguments `args` giving `out`, at `sizes`: an adapter's own charge, whether
    /// evolution placed it or a repair called it. It is positive for every adapter, whether the target is shorter,
    /// equal or longer, so the cost never rewards an adapter for its own sake.
    pub fn traffic(&self, k: &Kingdom6, reference: &str, args: &[Valued6], out: &Valued6, sizes: &BTreeMap<String, usize>) -> Result<u128, String> {
        self.row(reference)?.traffic.eval(&|x: &Factor6| {
            let (ty, props) = match x {
                Factor6::Out(_) => out,
                Factor6::In(i, _) => args.get(*i).ok_or_else(|| format!("our software has a bug: futhark_cost: the row {reference}'s traffic reads argument {i}"))?,
            };
            match x {
                Factor6::Out(p) | Factor6::In(_, p) if p == "cells" => cells6(k, *ty, props, sizes),
                Factor6::Out(p) | Factor6::In(_, p) => known6(props.get(p).ok_or_else(|| format!("our software has a bug: a cost reads the property {p} of a value that has none"))?, sizes),
            }
        })
    }

    /// The traffic of a call a repair makes ([`crate::typed_environment::Call`]), by its adapter's row.
    pub fn call(&self, k: &Kingdom6, c: &crate::typed_environment::Call, sizes: &BTreeMap<String, usize>) -> Result<u128, String> {
        let s = k.symbol_named(&c.adapter).ok_or_else(|| format!("our software has a bug: a repair calls {}, which is no symbol", c.adapter))?;
        let args: Vec<Valued6> = k.inputs(s).iter().zip(&c.args).map(|(ty, p)| (*ty, p.clone())).collect();
        self.traffic(k, k.reference(s), &args, &(k.output(s), c.out.clone()), sizes)
    }
}

/// The value of a property expression at `sizes`: `None` for `?` (and an argument's property, which a decoded node's
/// properties never hold).
pub fn size6(e: &PropertyExpr, sizes: &BTreeMap<String, usize>) -> Result<Option<i64>, String> {
    Ok(match e {
        PropertyExpr::Size(n) => Some(*sizes.get(n).ok_or_else(|| format!("our software has a bug: the size {n} has no value"))? as i64),
        PropertyExpr::Literal(v) => Some(*v),
        PropertyExpr::Min(args) | PropertyExpr::Max(args) => {
            let mut best: Option<i64> = None;
            for a in args {
                match size6(a, sizes)? {
                    Some(v) => best = Some(best.map_or(v, |l| if matches!(e, PropertyExpr::Min(_)) { l.min(v) } else { l.max(v) })),
                    None => return Ok(None),
                }
            }
            best
        }
        PropertyExpr::Sum(terms) => {
            let mut total = 0i64;
            for t in terms {
                match size6(t, sizes)? {
                    Some(v) => total = total.checked_add(v).ok_or("a size sum overflows")?,
                    None => return Ok(None),
                }
            }
            Some(total)
        }
        _ => None,
    })
}

/// A property expression's value at `sizes` for a cost or a work bound. A `?` LENGTH IS CHARGED AT THE LARGEST SIZE
/// IN SCOPE (the largest value in `sizes`); inside a minimum or a sum it takes that value too. An argument's property
/// (which a decoded node's properties never hold) is a bug.
fn known6(e: &PropertyExpr, sizes: &BTreeMap<String, usize>) -> Result<u128, String> {
    fn at(e: &PropertyExpr, sizes: &BTreeMap<String, usize>) -> Result<u128, String> {
        Ok(match e {
            PropertyExpr::Unknown => sizes.values().max().map(|v| *v as u128).ok_or_else(|| format!("our software has a bug: the size {e} is charged with no size in scope"))?,
            PropertyExpr::Input { .. } => return Err(format!("our software has a bug: the size {e} names an argument where a cost or a work bound reads it")),
            PropertyExpr::Min(args) => {
                let mut least: Option<u128> = None;
                for a in args {
                    let v = at(a, sizes)?;
                    least = Some(least.map_or(v, |l| l.min(v)));
                }
                least.ok_or_else(|| format!("our software has a bug: the size {e} is a minimum of nothing"))?
            }
            PropertyExpr::Sum(terms) => {
                let mut total = 0u128;
                for t in terms {
                    total = total.checked_add(at(t, sizes)?).ok_or("a size sum overflows")?;
                }
                total
            }
            PropertyExpr::Size(_) | PropertyExpr::Literal(_) => {
                let v = size6(e, sizes)?.ok_or_else(|| format!("our software has a bug: the size {e} has no value"))?;
                u128::try_from(v).map_err(|_| format!("our software has a bug: the size {e} is {v}"))?
            }
            _ => return Err(format!("our software has a bug: the size {e} is no sum or minimum of sizes, which a cost reads")),
        })
    }
    at(e, sizes)
}

/// The elements of a value of data type `ty` with properties `props`: an array's (the product of its data type's
/// properties), 1 for a scalar, a tuple's components, 0 for a function.
pub fn cells6(k: &Kingdom6, ty: Ty, props: &BTreeMap<String, PropertyExpr>, sizes: &BTreeMap<String, usize>) -> Result<u128, String> {
    let d = k.data_type(ty).ok_or_else(|| format!("our software has a bug: {ty:?} is no data type of {}", k.kingdom))?;
    match &d.kind {
        DataKind::Array { .. } => {
            let mut cells = 1u128;
            for p in &d.properties {
                let e = props.get(p).ok_or_else(|| format!("our software has a bug: a {} has no property {p}", d.name))?;
                cells = cells.checked_mul(known6(e, sizes)?).ok_or("a cell count overflows u128")?;
            }
            Ok(cells)
        }
        DataKind::Tuple { components } => Ok(components.len() as u128),
        DataKind::Function { .. } => Ok(0),
        DataKind::Scalar => Ok(1),
    }
}

/// The node a decoded node renders as: itself, or (a substitution by an input) that input's, followed down.
pub fn rendered6(n: &Node6) -> &Node6 {
    match n.substituted {
        Some(Substituted { by: Substitution::Input(p), .. }) => n.kids.get(p as usize).map_or(n, rendered6),
        _ => n,
    }
}

/// The trips of a binder node (its trip argument's subtree runs once a trip: its first argument, a size; one fewer
/// for a loop from 1), `None` for a node with no trip argument.
pub fn trips6(k: &Kingdom6, n: &Node6, sizes: &BTreeMap<String, usize>) -> Result<Option<u128>, String> {
    if k.trip(n.symbol).is_none() {
        return Ok(None);
    }
    let size = n.kids.first().and_then(|c| c.properties.get("value")).ok_or_else(|| format!("our software has a bug: the binder {} has no size argument", k.name(n.symbol)))?;
    let v = known6(size, sizes)?;
    Ok(Some(if matches!(k.reference(n.symbol), "M0041" | "M0074" | "M0084") { v.saturating_sub(1) } else { v }))
}

/// The traffic of every adapter the repairs of node `n` call, at the node (`body` false) or in its trip argument
/// (`body` true, which the caller charges once a trip).
pub fn calls6(k: &Kingdom6, table: &CostTable6, n: &Node6, body: bool, sizes: &BTreeMap<String, usize>) -> Result<u128, String> {
    let trip = k.trip(n.symbol);
    let mut total = 0u128;
    for (at, c) in k.decoder.node_calls(n)? {
        if (at.is_some() && at == trip) == body {
            total = total.checked_add(table.call(k, &c, sizes)?).ok_or("futhark_cost: a master 6 cost overflows u128")?;
        }
    }
    Ok(total)
}

/// The static cost of a decoded master 6 tree at `sizes` (above): its traffic, adapters included, allocations and
/// longest serial chain.
pub fn program_cost6(k: &Kingdom6, table: &CostTable6, decoding: &Decoding, sizes: &BTreeMap<String, usize>) -> Result<Score, String> {
    struct Walk<'a> {
        k: &'a Kingdom6,
        table: &'a CostTable6,
        sizes: &'a BTreeMap<String, usize>,
        traffic: u128,
        alloc: u128,
        depth: u128,
    }
    impl Walk<'_> {
        /// A node is a LEAF (always materialised: an input, a literal, a constant) when its symbol is no function or
        /// takes no argument, or when it renders as its data type's constant.
        fn leaf(&self, n: &Node6) -> bool {
            matches!(n.substituted, Some(Substituted { by: Substitution::Constant, .. })) || n.kids.is_empty() || self.k.role(n.symbol) != crate::geneframe::Role::Function
        }
        fn eval(&self, f: &Formula6, n: &Node6, ops: &[BTreeMap<String, PropertyExpr>]) -> Result<u128, String> {
            f.eval(&|x: &Factor6| -> Result<u128, String> {
                let (ty, props) = match x {
                    Factor6::Out(_) => (n.data_type, &n.properties),
                    Factor6::In(i, _) => (n.kids.get(*i).ok_or("our software has a bug: a cost reads an argument past the node's")?.data_type, ops.get(*i).ok_or("our software has a bug: a cost reads an argument past the node's")?),
                };
                match x {
                    Factor6::Out(p) | Factor6::In(_, p) if p == "cells" => cells6(self.k, ty, props, self.sizes),
                    Factor6::Out(p) | Factor6::In(_, p) => known6(props.get(p).ok_or_else(|| format!("our software has a bug: a cost reads the property {p} of a value that has none"))?, self.sizes),
                }
            })
        }
        fn visit(&mut self, n: &Node6, mult: u128, serial: u128, materialised: bool) -> Result<(), String> {
            let n = rendered6(n);
            if n.substituted.is_some() {
                return Ok(());
            }
            let row = self.table.row(self.k.reference(n.symbol))?;
            let m = |x: u128, by: u128| x.checked_mul(by).ok_or_else(|| "futhark_cost: a master 6 cost overflows u128".to_string());
            if materialised || self.leaf(n) {
                self.traffic += m(self.eval(&row.write, n, &[])?, mult)?;
                self.alloc += m(self.eval(&row.alloc, n, &[])?, mult)?;
            }
            let ops = self.k.decoder.adapted_operands(n)?;
            if !row.traffic.is_zero() {
                self.traffic += m(self.eval(&row.traffic, n, &ops)?, mult)?;
            }
            let trips = trips6(self.k, n, self.sizes)?;
            self.traffic += m(calls6(self.k, self.table, n, false, self.sizes)?, mult)?;
            self.traffic += m(calls6(self.k, self.table, n, true, self.sizes)?, m(mult, trips.unwrap_or(1))?)?;
            let kids_mat: Vec<bool> = n.kids.iter().map(|c| self.leaf(rendered6(c)) || !row.absorb).collect();
            for (i, read) in row.reads.iter().enumerate() {
                if kids_mat[i] {
                    self.traffic += m(self.eval(read, n, &ops)?, mult)?;
                }
            }
            if !row.depth.is_zero() {
                self.depth = self.depth.max(m(self.eval(&row.depth, n, &ops)?, serial)?);
            }
            let serial_body = trips.is_some() && !row.depth.is_zero();
            let trip = self.k.trip(n.symbol);
            for (i, c) in n.kids.iter().enumerate() {
                let here = trip == Some(i as u32);
                let (km, ks) = match (here, trips) {
                    (true, Some(t)) => (m(mult, t)?, if serial_body { m(serial, t)? } else { serial }),
                    _ => (mult, serial),
                };
                self.visit(c, km, ks, kids_mat[i])?;
            }
            Ok(())
        }
    }
    let mut w = Walk { k, table, sizes, traffic: 0, alloc: 0, depth: 0 };
    w.visit(&decoding.root, 1, 1, true)?;
    for c in k.decoder.calls(&k.entry, decoding)?.iter().filter(|c| c.path.is_none()) {
        w.traffic += table.call(k, c, sizes)?;
    }
    let u = |x: u128| u64::try_from(x).map_err(|_| "futhark_cost: a master 6 cost overflows u64".to_string());
    Ok(Score { traffic: u(w.traffic)?, alloc: u(w.alloc)?, depth: u(w.depth)? })
}


#[cfg(test)]
mod tests {
    use super::*;

    /// A `?` LENGTH IS CHARGED AT THE LARGEST SIZE IN SCOPE (F3 review finding 5), inside a minimum and a sum too; a
    /// known size is its value.
    #[test]
    fn a_question_mark_is_charged_at_the_largest_size() {
        let sizes: BTreeMap<String, usize> = [("n", 1000), ("k", 10), ("d", 3)].into_iter().map(|(a, b)| (a.to_string(), b)).collect();
        assert_eq!(known6(&PropertyExpr::Unknown, &sizes), Ok(1000));
        assert_eq!(known6(&PropertyExpr::Min(vec![PropertyExpr::Size("k".into()), PropertyExpr::Unknown]), &sizes), Ok(10));
        assert_eq!(known6(&PropertyExpr::Sum(vec![PropertyExpr::Unknown, PropertyExpr::Literal(1)]), &sizes), Ok(1001));
        assert_eq!(known6(&PropertyExpr::Size("d".into()), &sizes), Ok(3));
        assert!(known6(&PropertyExpr::Unknown, &BTreeMap::new()).is_err(), "no size in scope is a bug");
    }
}