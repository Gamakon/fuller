/// Master 6's cost table, generated by `gen_tables.py` and committed like the master.
const COSTS6_TSV: &str = include_str!("../kingdoms/futhark/master/6/costs.tsv");

/// The columns of [`COSTS6_TSV`].
const COSTS6_COLUMNS: [&str; 9] = ["kind", "ref", "name", "reads", "write", "alloc", "depth", "absorb", "traffic"];

/// One factor of a master 6 cost formula.
#[derive(Debug, Clone, PartialEq, Eq)]
enum Factor6 {
    /// A property of the row's result (`out.len`, `out.cells`).
    Out(String),
    /// A property of an argument as the node's adapters leave it (`in1.cells`).
    In(usize, String),
    /// The cells of the operand an adapter fits, at its target length.
    Fitted,
}

/// A master 6 cost formula: a sum of products of an integer coefficient and factors.
#[derive(Debug, Clone, PartialEq, Eq, Default)]
pub struct Formula6 {
    terms: Vec<(u128, Vec<Factor6>)>,
}

impl Formula6 {
    /// Parse `0`, or a sum (`+`) of products (`*`) of integers, `out.<p>`, `in<k>.<p>` and `fitted.cells`.
    fn parse(text: &str) -> Result<Formula6, String> {
        let bad = || format!("our software has a bug: futhark_cost: the master 6 cost formula {text:?}");
        if text == "0" {
            return Ok(Formula6::default());
        }
        let mut terms = Vec::new();
        for term in text.split('+') {
            let mut coefficient = 1u128;
            let mut factors = Vec::new();
            for f in term.split('*') {
                if let Ok(c) = f.parse::<u128>() {
                    coefficient = coefficient.checked_mul(c).ok_or_else(bad)?;
                } else if f == "fitted.cells" {
                    factors.push(Factor6::Fitted);
                } else if let Some(p) = f.strip_prefix("out.") {
                    factors.push(Factor6::Out(p.to_string()));
                } else if let Some((k, p)) = f.strip_prefix("in").and_then(|r| r.split_once('.')) {
                    factors.push(Factor6::In(k.parse().map_err(|_| bad())?, p.to_string()));
                } else {
                    return Err(bad());
                }
            }
            terms.push((coefficient, factors));
        }
        Ok(Formula6 { terms })
    }

    /// The formula's value, each factor's by `value`.
    fn eval(&self, value: &dyn Fn(&Factor6) -> Result<u128, String>) -> Result<u128, String> {
        let overflow = || "futhark_cost: a master 6 cost overflows u128".to_string();
        let mut total = 0u128;
        for (c, factors) in &self.terms {
            let mut term = *c;
            for f in factors {
                term = term.checked_mul(value(f)?).ok_or_else(overflow)?;
            }
            total = total.checked_add(term).ok_or_else(overflow)?;
        }
        Ok(total)
    }

    /// Whether the formula is the zero formula.
    fn is_zero(&self) -> bool {
        self.terms.is_empty()
    }
}

/// The cost of one master 6 row.
#[derive(Debug, Clone)]
pub struct RowCost6 {
    /// What it reads from each argument that is materialised, in argument order.
    reads: Vec<Formula6>,
    /// What it writes, and allocates, when it is materialised itself.
    write: Formula6,
    alloc: Formula6,
    /// Its serial depth.
    depth: Formula6,
    /// Whether it is elementwise, and so absorbs its arguments.
    absorb: bool,
}

/// Master 6's cost table: each master row's cost by its ref, and each adapter's traffic by its name.
#[derive(Debug, Clone)]
pub struct CostTable6 {
    rows: BTreeMap<String, RowCost6>,
    adapters: BTreeMap<String, Formula6>,
}

impl CostTable6 {
    /// Load the table, and check that every symbol of `k` (by its master row) and every adapter of `k` has a line.
    pub fn load(k: &Kingdom6) -> Result<CostTable6, String> {
        let bug = |what: String| format!("our software has a bug: futhark_cost: master/6/costs.tsv: {what}");
        let mut lines = COSTS6_TSV.lines();
        let header: Vec<&str> = lines.next().unwrap_or("").split('\t').collect();
        if header != COSTS6_COLUMNS {
            return Err(bug(format!("the header is {header:?}, wants {COSTS6_COLUMNS:?}")));
        }
        let (mut rows, mut adapters) = (BTreeMap::new(), BTreeMap::new());
        for line in lines.filter(|l| !l.trim().is_empty()) {
            let f: Vec<&str> = line.split('\t').collect();
            if f.len() != COSTS6_COLUMNS.len() {
                return Err(bug(format!("the line {line:?} has {} columns", f.len())));
            }
            match f[0] {
                "row" => {
                    let reads = if f[3].is_empty() { Vec::new() } else { f[3].split(';').map(Formula6::parse).collect::<Result<Vec<_>, _>>()? };
                    let cost = RowCost6 { reads, write: Formula6::parse(f[4])?, alloc: Formula6::parse(f[5])?, depth: Formula6::parse(f[6])?, absorb: f[7] == "1" };
                    if rows.insert(f[1].to_string(), cost).is_some() {
                        return Err(bug(format!("the row {} has two lines", f[1])));
                    }
                }
                "adapter" => {
                    if adapters.insert(f[2].to_string(), Formula6::parse(f[8])?).is_some() {
                        return Err(bug(format!("the adapter {} has two lines", f[2])));
                    }
                }
                other => return Err(bug(format!("a line of the kind {other:?}"))),
            }
        }
        for s in &k.symbols {
            let r = rows.get(&s.reference).ok_or_else(|| bug(format!("the row {} ({}) has no cost", s.reference, s.name)))?;
            if r.reads.len() != s.inputs.len() {
                return Err(bug(format!("{} reads {} arguments and takes {}", s.name, r.reads.len(), s.inputs.len())));
            }
        }
        for a in &k.adapters {
            if !adapters.contains_key(&a.name) {
                return Err(bug(format!("the adapter {} has no cost", a.name)));
            }
        }
        Ok(CostTable6 { rows, adapters })
    }

    /// The cost of a master row, by its ref.
    pub fn row(&self, reference: &str) -> Result<&RowCost6, String> {
        self.rows.get(reference).ok_or_else(|| format!("our software has a bug: futhark_cost: the row {reference} has no cost"))
    }

    /// The traffic one rendered adapter adds, at `sizes`: the table's formula (a `fit` writes `fitted.cells`, the
    /// operand at its target length) plus, for a `fit`, the cells it reads of its operand at its source length. AN
    /// ADAPTER'S OWN CHARGE COVERS ITS FULL TRAFFIC and is always positive, whether the target is shorter, equal or
    /// longer, so the cost never rewards an adapter for its own sake; what a shorter array saves downstream is real work
    /// saved, and quality decides whether the program is right (master README section 10).
    pub fn charge(&self, k: &Kingdom6, c: &Charge6, sizes: &BTreeMap<String, usize>) -> Result<u128, String> {
        let f = self.adapters.get(&c.adapter).ok_or_else(|| format!("our software has a bug: futhark_cost: the adapter {} has no cost", c.adapter))?;
        let own = f.eval(&|x: &Factor6| match (x, &c.fitted) {
            (Factor6::Fitted, Some((ty, props))) => cells6(k, *ty, props, sizes),
            _ => Err(format!("our software has a bug: futhark_cost: the adapter {}'s cost reads {x:?}", c.adapter)),
        })?;
        let read = match &c.source {
            Some((ty, props)) => cells6(k, *ty, props, sizes)?,
            None => 0,
        };
        own.checked_add(read).ok_or_else(|| "futhark_cost: a master 6 cost overflows u128".to_string())
    }
}

/// The value of a property expression at `sizes`: `None` for `?` (and an argument's property, which a decoded node's
/// properties never hold).
pub fn size6(e: &PropertyExpr, sizes: &BTreeMap<String, usize>) -> Result<Option<i64>, String> {
    Ok(match e {
        PropertyExpr::Size(n) => Some(*sizes.get(n).ok_or_else(|| format!("our software has a bug: the size {n} has no value"))? as i64),
        PropertyExpr::Literal(v) => Some(*v),
        PropertyExpr::Unknown | PropertyExpr::Input { .. } => None,
        PropertyExpr::Min(args) => {
            let mut least: Option<i64> = None;
            for a in args {
                match size6(a, sizes)? {
                    Some(v) => least = Some(least.map_or(v, |l| l.min(v))),
                    None => return Ok(None),
                }
            }
            least
        }
        PropertyExpr::Sum(terms) => {
            let mut total = 0i64;
            for t in terms {
                match size6(t, sizes)? {
                    Some(v) => total = total.checked_add(v).ok_or("a size sum overflows")?,
                    None => return Ok(None),
                }
            }
            Some(total)
        }
    })
}

/// A property expression's value at `sizes` for a cost or a work bound. A `?` LENGTH IS CHARGED AT THE LARGEST SIZE
/// IN SCOPE (the largest value in `sizes`): the renderer spells it as a length Futhark computes at run time (a
/// `filter`'s, the minimum of two such), which the cost cannot know; inside a minimum or a sum it takes that value too.
/// An argument's property (which a decoded node's properties never hold) is a bug.
fn known6(e: &PropertyExpr, sizes: &BTreeMap<String, usize>) -> Result<u128, String> {
    fn at(e: &PropertyExpr, sizes: &BTreeMap<String, usize>) -> Result<u128, String> {
        Ok(match e {
            PropertyExpr::Unknown => sizes.values().max().map(|v| *v as u128).ok_or_else(|| format!("our software has a bug: the size {e} is charged with no size in scope"))?,
            PropertyExpr::Input { .. } => return Err(format!("our software has a bug: the size {e} names an argument where a cost or a work bound reads it")),
            PropertyExpr::Min(args) => {
                let mut least: Option<u128> = None;
                for a in args {
                    let v = at(a, sizes)?;
                    least = Some(least.map_or(v, |l| l.min(v)));
                }
                least.ok_or_else(|| format!("our software has a bug: the size {e} is a minimum of nothing"))?
            }
            PropertyExpr::Sum(terms) => {
                let mut total = 0u128;
                for t in terms {
                    total = total.checked_add(at(t, sizes)?).ok_or("a size sum overflows")?;
                }
                total
            }
            PropertyExpr::Size(_) | PropertyExpr::Literal(_) => {
                let v = size6(e, sizes)?.ok_or_else(|| format!("our software has a bug: the size {e} has no value"))?;
                u128::try_from(v).map_err(|_| format!("our software has a bug: the size {e} is {v}"))?
            }
        })
    }
    at(e, sizes)
}

/// The elements of a value of data type `ty` with properties `props`: an array's (the product of its data type's
/// properties), 1 for a scalar, a tuple's components, 0 for a function.
pub fn cells6(k: &Kingdom6, ty: Ty, props: &BTreeMap<String, PropertyExpr>, sizes: &BTreeMap<String, usize>) -> Result<u128, String> {
    let d = k.data_type(ty).ok_or_else(|| format!("our software has a bug: {ty:?} is no data type of {}", k.kingdom))?;
    match &d.kind {
        DataKind::Array { .. } => {
            let mut cells = 1u128;
            for (p, _) in &d.properties {
                let e = props.get(p).ok_or_else(|| format!("our software has a bug: a {} has no property {p}", d.name))?;
                cells = cells.checked_mul(known6(e, sizes)?).ok_or("a cell count overflows u128")?;
            }
            Ok(cells)
        }
        DataKind::Tuple { components } => Ok(components.len() as u128),
        DataKind::Function { .. } => Ok(0),
        DataKind::Scalar => Ok(1),
    }
}

/// One adapter a node renders: its name, the operand it adapts and, for a `fit`, that operand's data type and
/// properties as the fit leaves it.
#[derive(Debug, Clone, PartialEq)]
pub struct Charge6 {
    pub adapter: String,
    /// The operand adapted (its argument position; `None` at the root).
    pub operand: Option<usize>,
    pub fitted: Option<(Ty, BTreeMap<String, PropertyExpr>)>,
    /// For a `fit`, the operand's data type and properties before the fit (what the fit reads).
    pub source: Option<(Ty, BTreeMap<String, PropertyExpr>)>,
}

/// The tables' requirement rows of a master 6 kingdom, in the order G3's outcomes index them (each symbol's
/// `requires`, symbol order).
pub fn requirements6(k: &Kingdom6) -> Vec<&Requirement> {
    k.symbols.iter().flat_map(|s| s.requires.iter()).collect()
}

/// Whether a property expression has a Futhark spelling (the renderer's `futhark_size`): no `?` and no argument term.
fn spelled6(e: &PropertyExpr) -> bool {
    match e {
        PropertyExpr::Size(_) | PropertyExpr::Literal(_) => true,
        PropertyExpr::Min(xs) | PropertyExpr::Sum(xs) => xs.iter().all(spelled6),
        PropertyExpr::Unknown | PropertyExpr::Input { .. } => false,
    }
}

/// THE ADAPTERS A NODE RENDERS, as the renderer decides them (`futhark_table::Render6::adapt`, mirrored on the
/// properties): the failing requirements of `n` whose adapter runs at the body (`body`) or at the node, the node's
/// other adapters first and `clampix` last; each operand's properties (`ops`, the arguments' in order) as the adapters
/// leave them; and the adapters with what each fits. A `fit` to a length with no spelling leaves `?`. A failing
/// work bound is a bug (the node is substituted, and its adapters do not render).
pub fn adapters6(k: &Kingdom6, reqs: &[&Requirement], n: &Node6, body: bool, ops: &mut [BTreeMap<String, PropertyExpr>]) -> Result<Vec<Charge6>, String> {
    let bug = |what: String| format!("our software has a bug: {}: {what}", k.kingdom);
    let at_body = |name: &str| k.adapters.iter().find(|a| a.name == name).map(|a| a.runs_at == AdapterSite::Body);
    let failing: Vec<&Outcome> = n.outcomes.iter().filter(|o| !o.holds && o.adapter != "clampix").chain(n.outcomes.iter().filter(|o| !o.holds && o.adapter == "clampix")).collect();
    let tys: Vec<Ty> = n.kids.iter().map(|c| c.data_type).collect();
    let mut out = Vec::new();
    for o in failing {
        if at_body(&o.adapter).ok_or_else(|| bug(format!("the adapter {} is not in the master", o.adapter)))? != body {
            continue;
        }
        let q = *reqs.get(o.requirement).ok_or_else(|| bug(format!("the outcome names requirement {}", o.requirement)))?;
        let Subject::Input { position, property } = &q.subject else { return Err(bug(format!("the work bound fails at an unsubstituted node ({})", o.adapter))) };
        let (s, ps) = (*position as usize, property.as_str());
        let against = match &q.against {
            PropertyExpr::Input { position, property } => Some((*position as usize, property.as_str())),
            _ => None,
        };
        if s >= ops.len() || against.is_some_and(|(a, _)| a >= ops.len()) {
            return Err(bug(format!("the requirement {} {} {} reads an input past the node's {}", q.subject, q.relation.symbol(), q.against, ops.len())));
        }
        let mut fit = |x: usize, p: &str, to: PropertyExpr, ops: &mut [BTreeMap<String, PropertyExpr>]| {
            let source = Some((tys[x], ops[x].clone()));
            ops[x].insert(p.to_string(), to);
            out.push(Charge6 { adapter: o.adapter.clone(), operand: Some(x), fitted: Some((tys[x], ops[x].clone())), source });
        };
        match o.adapter.as_str() {
            "clampix" => out.push(Charge6 { adapter: o.adapter.clone(), operand: Some(s), fitted: None, source: None }),
            "fit" | "fit.body" | "fit.state" => {
                let to = if spelled6(&o.against) { o.against.clone() } else { PropertyExpr::Unknown };
                fit(s, ps, to, ops);
            }
            "fit.pair" => {
                let (j, pj) = against.ok_or_else(|| bug("fit.pair's requirement names no second input".to_string()))?;
                let t = PropertyExpr::min(vec![o.subject.clone(), o.against.clone()]);
                if spelled6(&t) {
                    for (x, px) in [(j, pj), (s, ps)] {
                        if ops[x].get(px) != Some(&t) {
                            fit(x, px, t.clone(), ops);
                        }
                    }
                } else {
                    fit(j, pj, PropertyExpr::Unknown, ops);
                    fit(s, ps, PropertyExpr::Unknown, ops);
                }
            }
            "fit.inner" => {
                let mut sides = vec![(s, ps, o.subject.clone())];
                if let Some((a, pa)) = against {
                    sides.push((a, pa, o.against.clone()));
                }
                let cols: Vec<usize> = (0..sides.len()).filter(|i| sides[*i].1 == "cols").collect();
                let t = match cols.as_slice() {
                    [_, _] => PropertyExpr::min(vec![o.subject.clone(), o.against.clone()]),
                    [0] => o.against.clone(),
                    [1] => o.subject.clone(),
                    _ => return Err(bug(format!("fit.inner's requirement {} names no inner dimension", q.subject))),
                };
                for i in cols {
                    let x = sides[i].0;
                    if ops[x].get("cols") != Some(&t) {
                        fit(x, "cols", t.clone(), ops);
                    }
                }
            }
            other => return Err(bug(format!("the adapter {other} renders at no node"))),
        }
    }
    Ok(out)
}

/// The node a decoded node renders as: itself, or (a substitution by an input) that input's, followed down.
pub fn rendered6(n: &Node6) -> &Node6 {
    match n.substituted {
        Some(Substituted { by: Substitution::Input(p), .. }) => n.kids.get(p as usize).map_or(n, rendered6),
        _ => n,
    }
}

/// The trips of a binder node (its first argument, a size; one fewer for a loop from 1), `None` for a node with no
/// trip argument.
pub fn trips6(k: &Kingdom6, n: &Node6, sizes: &BTreeMap<String, usize>) -> Result<Option<u128>, String> {
    let s = k.symbols.get(n.symbol as usize).ok_or_else(|| format!("our software has a bug: the tree names symbol {}", n.symbol))?;
    if s.trip.is_none() {
        return Ok(None);
    }
    let size = n.kids.first().and_then(|c| c.properties.get("value")).ok_or_else(|| format!("our software has a bug: the binder {} has no size argument", s.name))?;
    let v = known6(size, sizes)?;
    Ok(Some(if matches!(s.reference.as_str(), "M0041" | "M0074" | "M0084") { v.saturating_sub(1) } else { v }))
}

/// The static cost of a decoded master 6 tree at `sizes` (above): its traffic, adapters included, allocations and
/// longest serial chain.
pub fn program_cost6(k: &Kingdom6, table: &CostTable6, decoding: &Decoding, sizes: &BTreeMap<String, usize>) -> Result<Score, String> {
    struct Walk<'a> {
        k: &'a Kingdom6,
        table: &'a CostTable6,
        reqs: Vec<&'a Requirement>,
        sizes: &'a BTreeMap<String, usize>,
        traffic: u128,
        alloc: u128,
        depth: u128,
    }
    impl Walk<'_> {
        /// A node is a LEAF (always materialised: an input, a literal, a constant) when its symbol is no function or
        /// takes no argument, or when it renders as its data type's constant.
        fn leaf(&self, n: &Node6) -> bool {
            matches!(n.substituted, Some(Substituted { by: Substitution::Constant, .. })) || n.kids.is_empty() || self.k.symbols.get(n.symbol as usize).is_none_or(|s| s.kind != Kind6::Function)
        }
        fn eval(&self, f: &Formula6, n: &Node6, ops: &[BTreeMap<String, PropertyExpr>]) -> Result<u128, String> {
            f.eval(&|x: &Factor6| -> Result<u128, String> {
                let (ty, props) = match x {
                    Factor6::Out(_) => (n.data_type, &n.properties),
                    Factor6::In(i, _) => (n.kids.get(*i).ok_or("our software has a bug: a cost reads an argument past the node's")?.data_type, ops.get(*i).ok_or("our software has a bug: a cost reads an argument past the node's")?),
                    Factor6::Fitted => return Err("our software has a bug: a row's cost reads fitted.cells".into()),
                };
                match x {
                    Factor6::Out(p) | Factor6::In(_, p) if p == "cells" => cells6(self.k, ty, props, self.sizes),
                    Factor6::Out(p) | Factor6::In(_, p) => known6(props.get(p).ok_or_else(|| format!("our software has a bug: a cost reads the property {p} of a value that has none"))?, self.sizes),
                    Factor6::Fitted => Err("our software has a bug: a row's cost reads fitted.cells".into()),
                }
            })
        }
        fn visit(&mut self, n: &Node6, mult: u128, serial: u128, materialised: bool) -> Result<(), String> {
            let n = rendered6(n);
            if n.substituted.is_some() {
                return Ok(());
            }
            let sym = self.k.symbols.get(n.symbol as usize).ok_or_else(|| format!("our software has a bug: the tree names symbol {}", n.symbol))?;
            let row = self.table.row(&sym.reference)?;
            let m = |x: u128, by: u128| x.checked_mul(by).ok_or_else(|| "futhark_cost: a master 6 cost overflows u128".to_string());
            if materialised || self.leaf(n) {
                self.traffic += m(self.eval(&row.write, n, &[])?, mult)?;
                self.alloc += m(self.eval(&row.alloc, n, &[])?, mult)?;
            }
            let mut ops: Vec<BTreeMap<String, PropertyExpr>> = n.kids.iter().map(|c| rendered6(c).properties.clone()).collect();
            let trips = trips6(self.k, n, self.sizes)?;
            for (body, by) in [(false, mult), (true, m(mult, trips.unwrap_or(1))?)] {
                for c in adapters6(self.k, &self.reqs, n, body, &mut ops)? {
                    self.traffic += m(self.table.charge(self.k, &c, self.sizes)?, by)?;
                }
            }
            let kids_mat: Vec<bool> = n.kids.iter().map(|c| self.leaf(rendered6(c)) || !row.absorb).collect();
            for (i, read) in row.reads.iter().enumerate() {
                if kids_mat[i] {
                    self.traffic += m(self.eval(read, n, &ops)?, mult)?;
                }
            }
            if !row.depth.is_zero() {
                self.depth = self.depth.max(m(self.eval(&row.depth, n, &ops)?, serial)?);
            }
            let serial_body = trips.is_some() && !row.depth.is_zero();
            for (i, c) in n.kids.iter().enumerate() {
                let here = sym.trip == Some(i as u32);
                let (km, ks) = match (here, trips) {
                    (true, Some(t)) => (m(mult, t)?, if serial_body { m(serial, t)? } else { serial }),
                    _ => (mult, serial),
                };
                self.visit(c, km, ks, kids_mat[i])?;
            }
            Ok(())
        }
    }
    let mut w = Walk { k, table, reqs: requirements6(k), sizes, traffic: 0, alloc: 0, depth: 0 };
    w.visit(&decoding.root, 1, 1, true)?;
    let mut root = rendered6(&decoding.root).properties.clone();
    for o in decoding.root_outcomes.iter().filter(|o| !o.holds) {
        let q = k.root.requires.get(o.requirement).ok_or_else(|| format!("our software has a bug: the entry has no requirement {}", o.requirement))?;
        let source = Some((k.root.data_type, root.clone()));
        root.insert(q.property.clone(), o.against.clone());
        w.traffic += table.charge(k, &Charge6 { adapter: o.adapter.clone(), operand: None, fitted: Some((k.root.data_type, root.clone())), source }, sizes)?;
    }
    let u = |x: u128| u64::try_from(x).map_err(|_| "futhark_cost: a master 6 cost overflows u64".to_string());
    Ok(Score { traffic: u(w.traffic)?, alloc: u(w.alloc)?, depth: u(w.depth)? })
}

#[cfg(test)]
mod tests {
    use super::*;
    use crate::futhark_table::FutharkKingdom;
    use crate::typed_gep::{express, GeneLayout};

    fn kingdom() -> FutharkKingdom {
        FutharkKingdom::load().expect("the Futhark tables load")
    }

    fn table(k: &FutharkKingdom) -> CostTable {
        CostTable::load(k).expect("the cost table loads")
    }

    fn sizes() -> BTreeMap<String, usize> {
        [("m".to_string(), 3usize), ("n".to_string(), 2), ("p".to_string(), 4)].into_iter().collect()
    }

    /// A tree of one row over the given trees.
    fn tree_with(k: &FutharkKingdom, name: &str, kids: Vec<Tree>) -> Tree {
        let symbol = k
            .rows
            .iter()
            .position(|r| r.name == name)
            .unwrap_or_else(|| panic!("the kingdom has no row {name}")) as u32;
        Tree { symbol, const_index: None, kids }
    }

    /// A leaf: a row with no children.
    fn leaf(k: &FutharkKingdom, name: &str) -> Tree {
        tree_with(k, name, Vec::new())
    }

    /// `map` with the identity row function over a matrix.
    fn map_over(k: &FutharkKingdom, class: &str, matrix: &str) -> Tree {
        tree_with(
            k,
            &format!("map_rows@{class}"),
            vec![leaf(k, "fn.arr_f32_arr_f32.id"), leaf(k, matrix)],
        )
    }

    #[test]
    fn every_row_has_a_cost() {
        let k = kingdom();
        let t = table(&k);
        for row in &k.rows {
            t.of(&row.name).unwrap_or_else(|e| panic!("{e}"));
        }
    }

    #[test]
    fn a_polynomial_is_parsed_and_evaluated() {
        let roles: Vec<String> = vec!["m".to_string(), "n".to_string()];
        let p = Poly::parse("2*n*m+n", &roles).expect("the polynomial parses");
        let sizes: BTreeMap<String, usize> = [("m".to_string(), 3usize), ("n".to_string(), 2)].into_iter().collect();
        assert_eq!(p.eval(&sizes).expect("the polynomial evaluates"), 2 * 2 * 3 + 2);
    }

    #[test]
    fn a_map_over_an_input_reads_it_and_writes_it() {
        let k = kingdom();
        let t = table(&k);
        // `map` over a 2x3 matrix: 6 elements read, 6 written.
        let tree = map_over(&k, "mat.n.m", "mat.n.m.input");
        let cost = program_cost(&tree, &k, &t).expect("the cost is computed");
        let score = score_at(&cost, &sizes()).expect("the score is computed");
        assert_eq!(score.traffic, 12, "six read and six written");
        assert_eq!(score.alloc, 6, "the result is six elements of fresh memory");
        assert_eq!(score.depth, 0, "no reduction");
    }

    #[test]
    fn a_fused_chain_costs_less_than_an_unfused_one() {
        let k = kingdom();
        let t = table(&k);
        // `map f (map g A)`: the inner map is absorbed, so the chain costs one
        // read of A and one write of the result — 6 and 6, at 2x3.
        let fused = tree_with(
            &k,
            "map_rows@mat.n.m",
            vec![
                leaf(&k, "fn.arr_f32_arr_f32.id"),
                map_over(&k, "mat.n.m", "mat.n.m.input"),
            ],
        );
        let fused_cost = program_cost(&fused, &k, &t).expect("costed");
        let fused_score = score_at(&fused_cost, &sizes()).expect("scored");
        assert_eq!(fused_score.traffic, 12, "six read and six written");
        assert_eq!(fused_score.alloc, 6, "one result, and no intermediate");

        // `transpose (map g A)`: the inner map is materialised, because
        // `transpose` is not elementwise — so the intermediate is written
        // and read again: 24 and 12.
        let unfused = tree_with(
            &k,
            "transpose@mat.m.n",
            vec![map_over(&k, "mat.n.m", "mat.n.m.input")],
        );
        let unfused_cost = program_cost(&unfused, &k, &t).expect("costed");
        let unfused_score = score_at(&unfused_cost, &sizes()).expect("scored");
        assert_eq!(unfused_score.traffic, 24, "read, written, read, written");
        assert_eq!(unfused_score.alloc, 12, "the intermediate and the result");
        assert!(
            fused_score.traffic < unfused_score.traffic,
            "the fused chain costs {} and the unfused one {}",
            fused_score.traffic,
            unfused_score.traffic
        );
    }

    /// The matmul is charged the TILED traffic: each operand read once.
    #[test]
    fn the_matmul_is_charged_the_tiled_traffic() {
        let k = kingdom();
        let t = table(&k);
        let tree = tree_with(
            &k,
            "matmul@mat.n.mxmat.m.p",
            vec![leaf(&k, "mat.n.m.input"), leaf(&k, "mat.m.p.input")],
        );
        let cost = program_cost(&tree, &k, &t).expect("the cost is computed");
        let score = score_at(&cost, &sizes()).expect("the score is computed");
        // n*m + m*p read, n*p written, with n=2, m=3, p=4.
        assert_eq!(score.traffic, 2 * 3 + 3 * 4 + 2 * 4);
        assert_eq!(score.alloc, 2 * 4);
        assert_eq!(score.depth, 3, "the reduction is three long");
    }

    /// A random gene's cost is computable — the model never panics on a
    /// program the engine can express.
    ///
    /// A random gene may express a program that is *only* the interface's
    /// input, and such a program costs nothing: the input is read, never
    /// written. So the test says that the cost is computable for every
    /// gene, and that the programs that do some work cost something.
    #[test]
    fn a_random_gene_can_be_costed() {
        let k = kingdom();
        let t = table(&k);
        let contract = k.relations().check().expect("the contract");
        let root = k.ty("mat.n.p").expect("the root class");
        let layout = GeneLayout::from_program_size(&contract, root, 3).expect("layout");
        let const_len = k.const_len();
        let mut rng: u64 = 0xC057_1E55_0001;
        let mut working = 0usize;
        for _ in 0..64 {
            let mut gene = vec![0u32; layout.width];
            for (pos, cell) in gene.iter_mut().enumerate() {
                let alphabet = layout.alphabet(&contract, pos, &const_len);
                rng = rng.wrapping_mul(6364136223846793005).wrapping_add(1442695040888963407);
                *cell = alphabet[((rng >> 33) as usize) % alphabet.len()];
            }
            let tree = express(&contract, &layout, &gene, &const_len).expect("legal").tree();
            let cost = program_cost(&tree, &k, &t).expect("the cost is computed");
            let score = score_at(&cost, &sizes()).expect("the score is computed");
            if score.traffic > 0 {
                working += 1;
            }
        }
        assert!(working > 0, "no random gene expressed a program that does any work");
    }

    /// A `?` LENGTH IS CHARGED AT THE LARGEST SIZE IN SCOPE (F3 review finding 5), inside a minimum and a sum too; a
    /// known size is its value.
    #[test]
    fn a_question_mark_is_charged_at_the_largest_size() {
        let sizes: BTreeMap<String, usize> = [("n", 1000), ("k", 10), ("d", 3)].into_iter().map(|(a, b)| (a.to_string(), b)).collect();
        assert_eq!(known6(&PropertyExpr::Unknown, &sizes), Ok(1000));
        assert_eq!(known6(&PropertyExpr::Min(vec![PropertyExpr::Size("k".into()), PropertyExpr::Unknown]), &sizes), Ok(10));
        assert_eq!(known6(&PropertyExpr::Sum(vec![PropertyExpr::Unknown, PropertyExpr::Literal(1)]), &sizes), Ok(1001));
        assert_eq!(known6(&PropertyExpr::Size("d".into()), &sizes), Ok(3));
        assert!(known6(&PropertyExpr::Unknown, &BTreeMap::new()).is_err(), "no size in scope is a bug");
    }
}
