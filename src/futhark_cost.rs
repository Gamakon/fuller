/// The cost table, generated by `gen_tables.py` and committed like the
/// kingdom's other tables.
const COSTS_TSV: &str = include_str!("../kingdoms/futhark/costs.tsv");

/// A polynomial in the dimension roles.
///
/// A monomial is a map from a role to its exponent, so the polynomial does
/// not depend on any role *order*: `n*m` and `m*n` are the same monomial.
/// The coefficients are integers, and a cost is never negative, so they are
/// checked when they are built.
#[derive(Debug, Clone, PartialEq, Eq, Default)]
pub struct Poly {
    /// The terms: a monomial and a coefficient.
    terms: BTreeMap<BTreeMap<String, u32>, i64>,
}

impl Poly {
    /// The zero polynomial.
    pub fn zero() -> Poly {
        Poly { terms: BTreeMap::new() }
    }

    /// Whether the polynomial is zero.
    pub fn is_zero(&self) -> bool {
        self.terms.values().all(|c| *c == 0)
    }

    /// The sum of two polynomials.
    pub fn add(&self, other: &Poly) -> Poly {
        let mut terms = self.terms.clone();
        for (monomial, coefficient) in &other.terms {
            let entry = terms.entry(monomial.clone()).or_insert(0);
            *entry += coefficient;
        }
        terms.retain(|_, c| *c != 0);
        Poly { terms }
    }

    /// Parse a role polynomial: a sum of products, like `n*m+m*p` or `2*n*p`.
    pub fn parse(text: &str, known_roles: &[String]) -> Result<Poly, String> {
        let mut terms: BTreeMap<BTreeMap<String, u32>, i64> = BTreeMap::new();
        for term in text.split('+') {
            let term = term.trim();
            if term.is_empty() {
                return Err(format!("futhark_cost: {text:?} has an empty term"));
            }
            let mut monomial: BTreeMap<String, u32> = BTreeMap::new();
            let mut coefficient = 1i64;
            for factor in term.split('*') {
                let factor = factor.trim();
                if factor.is_empty() {
                    return Err(format!("futhark_cost: {text:?} has an empty factor"));
                }
                match factor.parse::<i64>() {
                    Ok(n) => {
                        if n < 0 {
                            return Err(format!("futhark_cost: {text:?} has a negative coefficient"));
                        }
                        coefficient *= n;
                    }
                    Err(_) => {
                        if !known_roles.iter().any(|r| r == factor) {
                            return Err(format!("futhark_cost: {text:?} names the unknown role {factor}"));
                        }
                        *monomial.entry(factor.to_string()).or_insert(0) += 1;
                    }
                }
            }
            let entry = terms.entry(monomial).or_insert(0);
            *entry += coefficient;
        }
        terms.retain(|_, c| *c != 0);
        Ok(Poly { terms })
    }

    /// The polynomial's value at a set of role sizes.
    pub fn eval(&self, sizes: &BTreeMap<String, usize>) -> Result<u64, String> {
        let mut total: u64 = 0;
        for (monomial, coefficient) in &self.terms {
            if *coefficient < 0 {
                return Err("futhark_cost: a cost polynomial has a negative coefficient".to_string());
            }
            let mut term = *coefficient as u64;
            for (role, exponent) in monomial {
                let size = sizes
                    .get(role)
                    .ok_or_else(|| format!("futhark_cost: the role {role} has no size"))?;
                let mut factor = *size as u64;
                for _ in 1..*exponent {
                    factor = factor
                        .checked_mul(*size as u64)
                        .ok_or_else(|| format!("futhark_cost: the role {role} overflows"))?;
                }
                term = term
                    .checked_mul(factor)
                    .ok_or_else(|| "futhark_cost: a cost overflows u64".to_string())?;
            }
            total = total
                .checked_add(term)
                .ok_or_else(|| "futhark_cost: a cost overflows u64".to_string())?;
        }
        Ok(total)
    }
}

/// The cost of one row.
#[derive(Debug, Clone)]
pub struct RowCost {
    /// The size of the row's output.
    pub vol: Poly,
    /// The elements the row reads, unfused.
    pub read: Poly,
    /// The elements the row writes.
    pub write: Poly,
    /// The elements the row allocates.
    pub alloc: Poly,
    /// The row's serial depth — the reduction's length, for a reduction.
    pub depth: Poly,
    /// Whether the row is elementwise, and so absorbs its input.
    pub absorb: bool,
}

/// The kingdom's cost table: what each row costs.
#[derive(Debug, Clone)]
pub struct CostTable {
    /// The roles, in the order the polynomials' exponents use.
    pub roles: Vec<String>,
    /// The cost of each row, by the row's name.
    rows: BTreeMap<String, RowCost>,
}

impl CostTable {
    /// Load the cost table, and check that every row of the kingdom has one.
    pub fn load(kingdom: &FutharkKingdom) -> Result<CostTable, String> {
        let roles = crate::futhark::roles(kingdom);
        let mut rows: BTreeMap<String, RowCost> = BTreeMap::new();
        for line in COSTS_TSV.lines().skip(1).filter(|l| !l.trim().is_empty()) {
            let f: Vec<&str> = line.split('\t').collect();
            if f.len() != 7 {
                return Err(format!("futhark_cost: the cost row {line:?} has {} columns, wants 7", f.len()));
            }
            let name = f[0].to_string();
            if rows.contains_key(&name) {
                return Err(format!("futhark_cost: the row {name} has two cost rows"));
            }
            let cost = RowCost {
                vol: Poly::parse(f[1], &roles)?,
                read: Poly::parse(f[2], &roles)?,
                write: Poly::parse(f[3], &roles)?,
                alloc: Poly::parse(f[4], &roles)?,
                depth: Poly::parse(f[5], &roles)?,
                absorb: f[6] == "1",
            };
            rows.insert(name, cost);
        }
        for row in &kingdom.rows {
            if !rows.contains_key(&row.name) {
                return Err(format!("futhark_cost: the row {} has no cost", row.name));
            }
        }
        Ok(CostTable { roles, rows })
    }

    /// The cost of a row.
    pub fn of(&self, row_name: &str) -> Result<&RowCost, String> {
        self.rows
            .get(row_name)
            .ok_or_else(|| format!("futhark_cost: the row {row_name} has no cost"))
    }
}

/// What a program costs.
#[derive(Debug, Clone)]
pub struct ProgramCost {
    /// The elements read and written.
    pub traffic: Poly,
    /// The elements of fresh memory.
    pub alloc: Poly,
    /// The serial depth of each reduction in the program.
    pub reductions: Vec<Poly>,
}

/// A node of the program, with its place in the tree.
#[derive(Debug, Clone)]
struct Node {
    /// The row's index in the kingdom.
    row: usize,
    /// The children, by node index.
    kids: Vec<usize>,
    /// The consumers, by node index.
    consumers: Vec<usize>,
}

/// The cost of a program: its traffic, its allocations and its reductions.
///
/// The tree is walked once; a node is **materialised** when it is the root,
/// when it is a terminal (the interface's own input), when it has more than
/// one consumer, or when its consumer is not elementwise. A materialised
/// node's write and allocation are charged, and a consumer reads it
/// separately. A node that is not materialised is *absorbed* by its
/// elementwise consumer: no write, no allocation, and no separate read.
pub fn program_cost(tree: &Tree, kingdom: &FutharkKingdom, table: &CostTable) -> Result<ProgramCost, String> {
    let mut nodes: Vec<Node> = Vec::new();
    let root = walk(tree, &mut nodes);

    for v in 0..nodes.len() {
        for kid in nodes[v].kids.clone() {
            nodes[kid].consumers.push(v);
        }
    }

    // Whether each node is elementwise, and so absorbs its input.
    let mut absorbing = vec![false; nodes.len()];
    for v in 0..nodes.len() {
        let name = &kingdom.rows[nodes[v].row].name;
        absorbing[v] = table.of(name)?.absorb;
    }

    // Whether each node is materialised: the root, a terminal (the
    // interface's own input), a node with more than one consumer, and a node
    // whose only consumer is not elementwise.
    let mut materialised = vec![false; nodes.len()];
    for v in 0..nodes.len() {
        materialised[v] = if v == root
            || kingdom.rows[nodes[v].row].kind == FutharkKind::Terminal
            || nodes[v].consumers.len() != 1
        {
            true
        } else {
            !absorbing[nodes[v].consumers[0]]
        };
    }

    let mut traffic = Poly::zero();
    let mut alloc = Poly::zero();
    let mut reductions: Vec<Poly> = Vec::new();

    for v in 0..nodes.len() {
        let name = &kingdom.rows[nodes[v].row].name;
        let cost = table.of(name)?;
        if materialised[v] {
            traffic = traffic.add(&cost.write);
            alloc = alloc.add(&cost.alloc);
        }
        for kid in &nodes[v].kids {
            if materialised[*kid] {
                let kid_cost = table.of(&kingdom.rows[nodes[*kid].row].name)?;
                traffic = traffic.add(&kid_cost.vol);
            }
        }
        if !cost.depth.is_zero() {
            reductions.push(cost.depth.clone());
        }
    }

    Ok(ProgramCost { traffic, alloc, reductions })
}

/// Walk the tree, numbering the nodes.
fn walk(t: &Tree, nodes: &mut Vec<Node>) -> usize {
    let id = nodes.len();
    nodes.push(Node { row: t.symbol as usize, kids: Vec::new(), consumers: Vec::new() });
    let mut kids = Vec::new();
    for kid in &t.kids {
        kids.push(walk(kid, nodes));
    }
    nodes[id].kids = kids;
    id
}

/// A program's cost, evaluated at a set of role sizes.
///
/// The three components are compared in order: less traffic wins; if the
/// traffic ties, fewer allocations; if that ties too, the shorter
/// reduction.
#[derive(Debug, Clone, Copy, PartialEq, Eq, PartialOrd, Ord)]
pub struct Score {
    /// The elements read and written.
    pub traffic: u64,
    /// The elements of fresh memory.
    pub alloc: u64,
    /// The longest reduction.
    pub depth: u64,
}

/// The score of a program at a set of role sizes.
pub fn score_at(cost: &ProgramCost, sizes: &BTreeMap<String, usize>) -> Result<Score, String> {
    let traffic = cost.traffic.eval(sizes)?;
    let alloc = cost.alloc.eval(sizes)?;
    let mut depth = 0u64;
    for reduction in &cost.reductions {
        depth = depth.max(reduction.eval(sizes)?);
    }
    Ok(Score { traffic, alloc, depth })
}

