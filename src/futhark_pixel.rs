/// One input of the interface: a uniform field of the shader.
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct Input {
    pub name: String,
    pub group: u32,
    pub binding: u32,
    /// The field's word offset in its block.
    pub word: usize,
    /// The Futhark variable the program reads it as (`u_speed`).
    pub spelling: String,
}

/// The interface of an instance, in the order of the input vector.
pub fn interface(inst: &Instance) -> Result<Vec<Input>, String> {
    let mut out = Vec::new();
    for line in inst.interface.lines().filter(|l| !l.starts_with('#') && !l.trim().is_empty()) {
        let f: Vec<&str> = line.split('\t').collect();
        if f.len() != 5 {
            return Err(format!("{}: the interface line {line:?} has {} fields, wants 5", inst.name, f.len()));
        }
        let num = |s: &str| s.parse::<usize>().map_err(|e| format!("{}: {line:?}: {e}", inst.name));
        out.push(Input { name: f[0].to_string(), group: num(f[1])? as u32, binding: num(f[2])? as u32, word: num(f[3])?, spelling: f[4].to_string() });
    }
    Ok(out)
}

/// The number of words of the input vector before the interface's inputs:
/// width, height, and the tile: its first column and row, its columns and rows.
pub const HEADER: usize = 6;

/// A rectangle of the picture one run draws.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub struct Tile {
    pub col0: u32,
    pub row0: u32,
    pub cols: u32,
    pub rows: u32,
}

/// The input vector of one tile of one case: `[width, height, col0, row0,
/// cols, rows]` and then every interface input, read from the case's uniform
/// blocks (`(group, binding, bytes)`) at its word.
pub fn inputs(iface: &[Input], blocks: &[(u32, u32, &[u8])], width: u32, height: u32, tile: Tile) -> Result<Vec<f32>, String> {
    let mut ps = vec![width as f32, height as f32, tile.col0 as f32, tile.row0 as f32, tile.cols as f32, tile.rows as f32];
    for i in iface {
        let (_, _, bytes) = blocks
            .iter()
            .find(|(g, b, _)| *g == i.group && *b == i.binding)
            .ok_or_else(|| format!("the case has no uniform block at group {} binding {} for {}", i.group, i.binding, i.name))?;
        let w = bytes.get(i.word * 4..i.word * 4 + 4).ok_or_else(|| format!("the block of {} has no word {}", i.name, i.word))?;
        ps.push(f32::from_le_bytes([w[0], w[1], w[2], w[3]]));
    }
    Ok(ps)
}

/// The whole program: the entry point binding the interface from the input
/// vector, around the rendered tree (an `image` root).
pub fn program(k: &FutharkKingdom, iface: &[Input], tree: &Tree) -> Result<String, String> {
    let root = k.rows.get(tree.symbol as usize).ok_or("the root is not a row")?;
    if k.dual(root.output).map(|d| d.dual.as_str()) != Some("image") {
        return Err(format!("the root {} is not an image", root.name));
    }
    let mut s = String::from("entry main (ps: []f32) : [][][3]f32 =\n");
    // The tile's sizes are i64 on the host; its offsets stay f32, because the
    // branch compiler's WGSL has no f32-to-i64 conversion inside a kernel
    // (`not_implemented(fptosi_f32_i64)`) and Futhark sinks a conversion used
    // only by the pixels into the kernel. Offsets below 2^24 add exactly.
    s.push_str("  let col0 = ps[2]\n  let row0 = ps[3]\n  let cols = i64.f32 ps[4]\n  let rows = i64.f32 ps[5]\n");
    s.push_str("  let u_width = ps[0]\n  let u_height = ps[1]\n");
    for (i, input) in iface.iter().enumerate() {
        s.push_str(&format!("  let {} = ps[{}]\n", input.spelling, HEADER + i));
    }
    s.push_str(&format!("  in {}\n", k.render(tree)?));
    Ok(s)
}

/// The node executions of one pixel: every node once, times the trips of the
/// loops it is inside (a loop row's body is its second-last argument and its
/// trip count the `count` argument before it). The exact bound of the
/// expressed tree, as `TrueKingdom::tree_work_bound` is for WGSL.
pub fn work_per_pixel(k: &FutharkKingdom, tree: &Tree) -> Result<u128, String> {
    fn walk(k: &FutharkKingdom, t: &Tree, mult: u128) -> Result<u128, String> {
        let row = k.rows.get(t.symbol as usize).ok_or("a symbol that is not a row")?;
        let mut sum = mult;
        if row.name.starts_with("loop") {
            let n = t.kids.len();
            let count = &t.kids[n - 3];
            let trips: u128 = k.rows[count.symbol as usize].spelling.parse().map_err(|e| format!("a count that is not a number: {e}"))?;
            for (i, kid) in t.kids.iter().enumerate() {
                sum += walk(k, kid, if i == n - 2 { mult * trips } else { mult })?;
            }
        } else {
            for kid in &t.kids {
                sum += walk(k, kid, mult)?;
            }
        }
        Ok(sum)
    }
    walk(k, tree, 1)
}

/// The tiles a picture is drawn in, so that no submit's bound (`work` a pixel
/// times the tile's pixels) exceeds `cap`: bands of whole rows when a row
/// fits, runs of columns within a row when it does not. One pixel over the cap
/// is a misconfigured experiment (named, never run).
pub fn tiles(work: u128, width: u32, height: u32, cap: u128) -> Result<Vec<Tile>, String> {
    if work > cap {
        return Err(format!("one pixel of this tree is bounded by {work} node executions, over the per-submit cap {cap}"));
    }
    let per = cap / work.max(1);
    let mut out = Vec::new();
    if per >= u128::from(width) {
        let rows = u32::try_from((per / u128::from(width)).min(u128::from(height))).unwrap_or(height).max(1);
        let mut r = 0;
        while r < height {
            let n = rows.min(height - r);
            out.push(Tile { col0: 0, row0: r, cols: width, rows: n });
            r += n;
        }
    } else {
        let cols = u32::try_from(per).unwrap_or(1).max(1);
        for r in 0..height {
            let mut c = 0;
            while c < width {
                let n = cols.min(width - c);
                out.push(Tile { col0: c, row0: r, cols: n, rows: 1 });
                c += n;
            }
        }
    }
    Ok(out)
}

/// Put a tile's `[rows][cols][3]` output into a picture's RGBA (each channel
/// rounded to a half, as the texture store rounds it; alpha 1).
pub fn place(rgba: &mut [f32], width: u32, tile: Tile, values: &[f32]) -> Result<(), String> {
    if values.len() != (tile.cols * tile.rows * 3) as usize {
        return Err(format!("a tile of {}x{} gave {} values", tile.cols, tile.rows, values.len()));
    }
    for y in 0..tile.rows {
        for x in 0..tile.cols {
            let v = &values[((y * tile.cols + x) * 3) as usize..][..3];
            let at = (((tile.row0 + y) * width + tile.col0 + x) * 4) as usize;
            rgba[at..at + 4].copy_from_slice(&[f16_round(v[0]), f16_round(v[1]), f16_round(v[2]), 1.0]);
        }
    }
    Ok(())
}

/// `x` rounded to the nearest half-float (ties to even), as a store into an
/// `rgba16float` texture rounds it, returned as the `f32` of that half.
pub fn f16_round(x: f32) -> f32 {
    crate_half::to_f32(crate_half::from_f32(x))
}

/// Half-float conversion, ties to even.
mod crate_half {
    pub fn from_f32(x: f32) -> u16 {
        let b = x.to_bits();
        let sign = ((b >> 16) & 0x8000) as u16;
        let exp = ((b >> 23) & 0xff) as i32;
        let man = b & 0x7f_ffff;
        if exp == 0xff {
            return sign | 0x7c00 | if man != 0 { 0x200 } else { 0 };
        }
        let e = exp - 127 + 15;
        if e >= 0x1f {
            return sign | 0x7c00;
        }
        if e <= 0 {
            if e < -10 {
                return sign;
            }
            let m = man | 0x80_0000;
            let shift = (14 - e) as u32;
            let half = m >> shift;
            let rem = m & ((1 << shift) - 1);
            let mid = 1 << (shift - 1);
            let rounded = if rem > mid || (rem == mid && half & 1 == 1) { half + 1 } else { half };
            return sign | rounded as u16;
        }
        let half = ((e as u32) << 10) | (man >> 13);
        let rem = man & 0x1fff;
        let rounded = if rem > 0x1000 || (rem == 0x1000 && half & 1 == 1) { half + 1 } else { half };
        sign | rounded as u16
    }

    pub fn to_f32(h: u16) -> f32 {
        let sign = if h & 0x8000 != 0 { -1.0f32 } else { 1.0 };
        let exp = i32::from((h >> 10) & 0x1f);
        let frac = f32::from(h & 0x3ff);
        match exp {
            0 => sign * frac * 2f32.powi(-24),
            31 => {
                if frac == 0.0 {
                    sign * f32::INFINITY
                } else {
                    f32::NAN
                }
            }
            e => sign * (1.0 + frac / 1024.0) * 2f32.powi(e - 15),
        }
    }
}

/// Compile a program with Futhark's sequential C backend (`futhark c`, the
/// released compiler) into `dir`; returns the executable. The reference
/// path beside the GPU's (`futhark_wgpu_host`).
pub fn compile_c(source: &str, dir: &std::path::Path) -> Result<std::path::PathBuf, String> {
    std::fs::create_dir_all(dir).map_err(|e| format!("mkdir {}: {e}", dir.display()))?;
    let fut = dir.join("prog.fut");
    std::fs::write(&fut, source).map_err(|e| format!("write {}: {e}", fut.display()))?;
    let exe = dir.join("prog_c");
    let out = crate::futhark_exec::output_with_timeout(
        std::process::Command::new("futhark").arg("c").arg(&fut).arg("-o").arg(&exe),
        std::time::Duration::from_secs(120),
        None,
    )?;
    if !out.status.success() {
        return Err(format!("futhark c failed:\n{}", String::from_utf8_lossy(&out.stderr)));
    }
    Ok(exe)
}

/// Run a compiled program (either backend's executable) on an input vector
/// and read its `[rows][cols][3]f32` back from Futhark's binary format.
pub fn run_exe(exe: &std::path::Path, ps: &[f32]) -> Result<Vec<f32>, String> {
    let out = crate::futhark_exec::output_with_timeout(
        std::process::Command::new(exe).arg("-b"),
        std::time::Duration::from_secs(120),
        Some(&crate::futhark_wgpu_host::input_text(ps)?),
    )?;
    if !out.status.success() {
        return Err(format!("{} failed:\n{}", exe.display(), String::from_utf8_lossy(&out.stderr)));
    }
    crate::futhark_wgpu_host::read_binary_f32(&out.stdout)
}

/// Draw a picture with a compiled program, tile by tile: on the GPU through
/// the shim (`gpu`, every pass timed by the GPU, which must be Metal) or with
/// a C-backend executable. Each tile's process runs the program `runs` times
/// (Futhark's `-r`, after its warm-up run) and the tile's time is the FASTEST
/// run's GPU nanoseconds (the sum of that run's timed passes); the picture's
/// time is the sum over its tiles (0 for the C backend). The fastest, because
/// the GPU's clock ramps up within a process: measured 2026-10-27 on the
/// reference at 64 x 64, the first runs of a process take 280 us and the last
/// 74 us, so a median moves with the ramp (pairs of the reference against
/// itself from 0.62 to 3.6), while the fastest of 40 runs was 73.3 to 74.2 us
/// over 8 processes. Returns the RGBA picture (halves, alpha 1) of
/// the last run and that time.
pub fn draw(exe: &std::path::Path, gpu: bool, ps_of: &dyn Fn(Tile) -> Result<Vec<f32>, String>, plan: &[Tile], width: u32, height: u32, runs: usize) -> Result<(Vec<f32>, f64), String> {
    let mut rgba = vec![0f32; (width * height * 4) as usize];
    let mut ns = 0.0;
    for &tile in plan {
        let ps = ps_of(tile)?;
        let values = if gpu {
            let run = crate::futhark_wgpu_host::run_program_times(exe, &ps, true, runs)?;
            let passes = &run.report.passes;
            // Futhark's `-r N` (N > 1) runs once more first, untimed by its
            // own clock: a warm-up. Its passes are in the report and are dropped.
            let total = runs + usize::from(runs > 1);
            if run.report.backend != "Metal" || passes.is_empty() || run.report.timed_passes() != passes.len() || passes.len() % total != 0 {
                return Err(format!("a tile did not run timed on Metal, {total} runs of equal passes: {:?}", run.report));
            }
            let per = passes.len() / total;
            let times: Vec<f64> = passes[(total - runs) * per..].chunks_exact(per).map(|c| c.iter().map(|p| p.2).sum::<f64>()).collect();
            ns += times.iter().cloned().fold(f64::INFINITY, f64::min);
            run.values
        } else {
            run_exe(exe, &ps)?
        };
        place(&mut rgba, width, tile, &values)?;
    }
    Ok((rgba, ns))
}

