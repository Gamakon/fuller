//! The pixel family of the shape kingdom's generator: a picture as a map over
//! the pixels of a scalar program (`kingdoms/futhark_shapes/gen_tables.py`,
//! section "THE PIXEL FAMILY"; one instance a shader, under
//! `kingdoms/futhark_shapes/pixel/<shader>/`).
//!
//! A cuneus image shader runs one invocation a pixel: it reads the pixel's
//! coordinates and its uniforms, runs bounded loops over scalar and vector
//! arithmetic, and stores a colour. Here that is a Futhark program
//!
//! ```text
//! map (\yi -> map (\xi -> let px = .. in let py = .. in <pixel block>) (iota w)) (iota rows)
//! ```
//!
//! whose pixel block is a chain of `let`s and bounded `loop`s over `f32`,
//! ending in `[r, g, b]`. The types carry every rule (scope, binding, the
//! loop bound, the result arity), so every gene expresses a program Futhark
//! accepts; the generator's witness tests check the table, and the tests here
//! check that Futhark agrees.
//!
//! The instance's tables are loaded into the [`FutharkFamily::Shape`] type
//! family: they are generated by the shape kingdom's generator and never share
//! a geneframe with the matrix kingdom.
//!
//! What this module holds: the loader, the program around an expressed tree
//! (the entry point binding the interface's inputs), the input vector of a
//! case, the work bound and the band plan that keeps every submit under the
//! GPU cap, a builder that writes a program written by hand as a tree of rows
//! (the reference volumepassage, [`VOLUMEPASSAGE_REFERENCE`]), the half-float
//! rounding of the output texture, and the instance's e-graph (one sort a
//! type, constants by their pool index).

