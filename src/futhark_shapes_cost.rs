//! The shape kingdom's **static cost**: what a program costs, as a
//! polynomial in the dimension roles.
//!
//! This is the fitness's cost half, and it is deliberately *not* a
//! measurement and *not* wall-clock time:
//!
//! * **Not wall-clock.** C-backend time does not transfer to the GPU:
//!   fusion and traversal counts matter differently there, and a search
//!   that optimises for the wrong machine is worse than no search. This
//!   model is the cheap *filter*; the cost that decides is measured on the
//!   GPU, in [`crate::futhark_shapes_gpu`].
//! * **Not a measurement.** The numbers come from the kingdom's own table
//!   (`kingdoms/futhark_shapes/costs.tsv`, generated), so they are a
//!   *model* that the table and the generator's witness tests keep honest,
//!   not a number that drifts with the machine.
//!
//! # What is charged
//!
//! Three things, all in elements:
//!
//! * **traffic** — elements read and written;
//! * **allocations** — elements of fresh memory;
//! * **serial depth** — the length of the longest reduction, which is what
//!   limits a GPU's parallelism.
//!
//! # The matmul is charged the TILED traffic
//!
//! Futhark 0.28.1 has no `matmul` intrinsic, so the kingdom brings its own,
//! and that helper is a nested map/reduce. On the GPU that shape is exactly
//! what the compiler's own tiler recognises: `gpuPipeline` runs `tileLoops`
//! (`Futhark/Optimise/TileLoops.hs`), and the block+register tiler
//! (`Futhark/Optimise/BlkRegTiling.hs`) names SGEMM as one of its target
//! patterns.
//!
//! So the `matmul` row is charged the traffic the **tiled** version
//! achieves — each operand element read once — and not the traffic the naive
//! nested map/reduce actually costs. The tiling is the compiler's business;
//! a cost model that charged for it would rank a program against a machine
//! it will never run on.
//!
//! # Fusion
//!
//! An **elementwise** row (`map_rows`, `map2_rows`) *absorbs* its input: a
//! chain of maps costs one traversal, not one per link. The rule is
//! structural, not a rewrite: a node whose only consumer is elementwise is
//! not materialised, so neither its write nor its allocation is charged, and
//! the consumer does not read it separately.
//!
//! The rule reaches further than a chain of maps: it absorbs *any* producer
//! into an elementwise consumer, a product or a transpose included, because
//! that is what Futhark's own SOAC fusion does — `map f (matmul A B)` is one
//! loop nest to the compiler, not two.
//!
//! A terminal is never absorbed — it is the interface's own input, and it
//! is always materialised.

use std::collections::BTreeMap;

use crate::futhark_kingdom::{FutharkKind, FutharkKingdom};
use crate::typed_gep::Tree;

/// The cost table, generated by `gen_tables.py` and committed like the
/// kingdom's other tables.
const COSTS_TSV: &str = include_str!("../kingdoms/futhark_shapes/costs.tsv");

/// A polynomial in the dimension roles.
///
/// A monomial is a map from a role to its exponent, so the polynomial does
/// not depend on any role *order*: `n*m` and `m*n` are the same monomial.
/// The coefficients are integers, and a cost is never negative, so they are
/// checked when they are built.
#[derive(Debug, Clone, PartialEq, Eq, Default)]
pub struct Poly {
    /// The terms: a monomial and a coefficient.
    terms: BTreeMap<BTreeMap<String, u32>, i64>,
}

impl Poly {
    /// The zero polynomial.
    pub fn zero() -> Poly {
        Poly { terms: BTreeMap::new() }
    }

    /// Whether the polynomial is zero.
    pub fn is_zero(&self) -> bool {
        self.terms.values().all(|c| *c == 0)
    }

    /// The sum of two polynomials.
    pub fn add(&self, other: &Poly) -> Poly {
        let mut terms = self.terms.clone();
        for (monomial, coefficient) in &other.terms {
            let entry = terms.entry(monomial.clone()).or_insert(0);
            *entry += coefficient;
        }
        terms.retain(|_, c| *c != 0);
        Poly { terms }
    }

    /// Parse a role polynomial: a sum of products, like `n*m+m*p` or `2*n*p`.
    pub fn parse(text: &str, known_roles: &[String]) -> Result<Poly, String> {
        let mut terms: BTreeMap<BTreeMap<String, u32>, i64> = BTreeMap::new();
        for term in text.split('+') {
            let term = term.trim();
            if term.is_empty() {
                return Err(format!("futhark_shapes_cost: {text:?} has an empty term"));
            }
            let mut monomial: BTreeMap<String, u32> = BTreeMap::new();
            let mut coefficient = 1i64;
            for factor in term.split('*') {
                let factor = factor.trim();
                if factor.is_empty() {
                    return Err(format!("futhark_shapes_cost: {text:?} has an empty factor"));
                }
                match factor.parse::<i64>() {
                    Ok(n) => {
                        if n < 0 {
                            return Err(format!("futhark_shapes_cost: {text:?} has a negative coefficient"));
                        }
                        coefficient *= n;
                    }
                    Err(_) => {
                        if !known_roles.iter().any(|r| r == factor) {
                            return Err(format!("futhark_shapes_cost: {text:?} names the unknown role {factor}"));
                        }
                        *monomial.entry(factor.to_string()).or_insert(0) += 1;
                    }
                }
            }
            let entry = terms.entry(monomial).or_insert(0);
            *entry += coefficient;
        }
        terms.retain(|_, c| *c != 0);
        Ok(Poly { terms })
    }

    /// The polynomial's value at a set of role sizes.
    pub fn eval(&self, sizes: &BTreeMap<String, usize>) -> Result<u64, String> {
        let mut total: u64 = 0;
        for (monomial, coefficient) in &self.terms {
            if *coefficient < 0 {
                return Err("futhark_shapes_cost: a cost polynomial has a negative coefficient".to_string());
            }
            let mut term = *coefficient as u64;
            for (role, exponent) in monomial {
                let size = sizes
                    .get(role)
                    .ok_or_else(|| format!("futhark_shapes_cost: the role {role} has no size"))?;
                let mut factor = *size as u64;
                for _ in 1..*exponent {
                    factor = factor
                        .checked_mul(*size as u64)
                        .ok_or_else(|| format!("futhark_shapes_cost: the role {role} overflows"))?;
                }
                term = term
                    .checked_mul(factor)
                    .ok_or_else(|| "futhark_shapes_cost: a cost overflows u64".to_string())?;
            }
            total = total
                .checked_add(term)
                .ok_or_else(|| "futhark_shapes_cost: a cost overflows u64".to_string())?;
        }
        Ok(total)
    }
}

/// The cost of one row.
#[derive(Debug, Clone)]
pub struct RowCost {
    /// The size of the row's output.
    pub vol: Poly,
    /// The elements the row reads, unfused.
    pub read: Poly,
    /// The elements the row writes.
    pub write: Poly,
    /// The elements the row allocates.
    pub alloc: Poly,
    /// The row's serial depth — the reduction's length, for a reduction.
    pub depth: Poly,
    /// Whether the row is elementwise, and so absorbs its input.
    pub absorb: bool,
}

/// The kingdom's cost table: what each row costs.
#[derive(Debug, Clone)]
pub struct CostTable {
    /// The roles, in the order the polynomials' exponents use.
    pub roles: Vec<String>,
    /// The cost of each row, by the row's name.
    rows: BTreeMap<String, RowCost>,
}

impl CostTable {
    /// Load the cost table, and check that every row of the kingdom has one.
    pub fn load(kingdom: &FutharkKingdom) -> Result<CostTable, String> {
        let roles = crate::futhark_shapes::roles(kingdom);
        let mut rows: BTreeMap<String, RowCost> = BTreeMap::new();
        for line in COSTS_TSV.lines().skip(1).filter(|l| !l.trim().is_empty()) {
            let f: Vec<&str> = line.split('\t').collect();
            if f.len() != 7 {
                return Err(format!("futhark_shapes_cost: the cost row {line:?} has {} columns, wants 7", f.len()));
            }
            let name = f[0].to_string();
            if rows.contains_key(&name) {
                return Err(format!("futhark_shapes_cost: the row {name} has two cost rows"));
            }
            let cost = RowCost {
                vol: Poly::parse(f[1], &roles)?,
                read: Poly::parse(f[2], &roles)?,
                write: Poly::parse(f[3], &roles)?,
                alloc: Poly::parse(f[4], &roles)?,
                depth: Poly::parse(f[5], &roles)?,
                absorb: f[6] == "1",
            };
            rows.insert(name, cost);
        }
        for row in &kingdom.rows {
            if !rows.contains_key(&row.name) {
                return Err(format!("futhark_shapes_cost: the row {} has no cost", row.name));
            }
        }
        Ok(CostTable { roles, rows })
    }

    /// The cost of a row.
    pub fn of(&self, row_name: &str) -> Result<&RowCost, String> {
        self.rows
            .get(row_name)
            .ok_or_else(|| format!("futhark_shapes_cost: the row {row_name} has no cost"))
    }
}

/// What a program costs.
#[derive(Debug, Clone)]
pub struct ProgramCost {
    /// The elements read and written.
    pub traffic: Poly,
    /// The elements of fresh memory.
    pub alloc: Poly,
    /// The serial depth of each reduction in the program.
    pub reductions: Vec<Poly>,
}

/// A node of the program, with its place in the tree.
#[derive(Debug, Clone)]
struct Node {
    /// The row's index in the kingdom.
    row: usize,
    /// The children, by node index.
    kids: Vec<usize>,
    /// The consumers, by node index.
    consumers: Vec<usize>,
}

/// The cost of a program: its traffic, its allocations and its reductions.
///
/// The tree is walked once; a node is **materialised** when it is the root,
/// when it is a terminal (the interface's own input), when it has more than
/// one consumer, or when its consumer is not elementwise. A materialised
/// node's write and allocation are charged, and a consumer reads it
/// separately. A node that is not materialised is *absorbed* by its
/// elementwise consumer: no write, no allocation, and no separate read.
pub fn program_cost(tree: &Tree, kingdom: &FutharkKingdom, table: &CostTable) -> Result<ProgramCost, String> {
    let mut nodes: Vec<Node> = Vec::new();
    let root = walk(tree, &mut nodes);

    for v in 0..nodes.len() {
        for kid in nodes[v].kids.clone() {
            nodes[kid].consumers.push(v);
        }
    }

    // Whether each node is elementwise, and so absorbs its input.
    let mut absorbing = vec![false; nodes.len()];
    for v in 0..nodes.len() {
        let name = &kingdom.rows[nodes[v].row].name;
        absorbing[v] = table.of(name)?.absorb;
    }

    // Whether each node is materialised: the root, a terminal (the
    // interface's own input), a node with more than one consumer, and a node
    // whose only consumer is not elementwise.
    let mut materialised = vec![false; nodes.len()];
    for v in 0..nodes.len() {
        materialised[v] = if v == root
            || kingdom.rows[nodes[v].row].kind == FutharkKind::Terminal
            || nodes[v].consumers.len() != 1
        {
            true
        } else {
            !absorbing[nodes[v].consumers[0]]
        };
    }

    let mut traffic = Poly::zero();
    let mut alloc = Poly::zero();
    let mut reductions: Vec<Poly> = Vec::new();

    for v in 0..nodes.len() {
        let name = &kingdom.rows[nodes[v].row].name;
        let cost = table.of(name)?;
        if materialised[v] {
            traffic = traffic.add(&cost.write);
            alloc = alloc.add(&cost.alloc);
        }
        for kid in &nodes[v].kids {
            if materialised[*kid] {
                let kid_cost = table.of(&kingdom.rows[nodes[*kid].row].name)?;
                traffic = traffic.add(&kid_cost.vol);
            }
        }
        if !cost.depth.is_zero() {
            reductions.push(cost.depth.clone());
        }
    }

    Ok(ProgramCost { traffic, alloc, reductions })
}

/// Walk the tree, numbering the nodes.
fn walk(t: &Tree, nodes: &mut Vec<Node>) -> usize {
    let id = nodes.len();
    nodes.push(Node { row: t.symbol as usize, kids: Vec::new(), consumers: Vec::new() });
    let mut kids = Vec::new();
    for kid in &t.kids {
        kids.push(walk(kid, nodes));
    }
    nodes[id].kids = kids;
    id
}

/// A program's cost, evaluated at a set of role sizes.
///
/// The three components are compared in order: less traffic wins; if the
/// traffic ties, fewer allocations; if that ties too, the shorter
/// reduction.
#[derive(Debug, Clone, Copy, PartialEq, Eq, PartialOrd, Ord)]
pub struct Score {
    /// The elements read and written.
    pub traffic: u64,
    /// The elements of fresh memory.
    pub alloc: u64,
    /// The longest reduction.
    pub depth: u64,
}

/// The score of a program at a set of role sizes.
pub fn score_at(cost: &ProgramCost, sizes: &BTreeMap<String, usize>) -> Result<Score, String> {
    let traffic = cost.traffic.eval(sizes)?;
    let alloc = cost.alloc.eval(sizes)?;
    let mut depth = 0u64;
    for reduction in &cost.reductions {
        depth = depth.max(reduction.eval(sizes)?);
    }
    Ok(Score { traffic, alloc, depth })
}

#[cfg(test)]
mod tests {
    use super::*;
    use crate::futhark_kingdom::FutharkKingdom;
    use crate::typed_gep::{express, GeneLayout};

    fn kingdom() -> FutharkKingdom {
        FutharkKingdom::load_shapes().expect("the shape tables load")
    }

    fn table(k: &FutharkKingdom) -> CostTable {
        CostTable::load(k).expect("the cost table loads")
    }

    fn sizes() -> BTreeMap<String, usize> {
        [("m".to_string(), 3usize), ("n".to_string(), 2), ("p".to_string(), 4)].into_iter().collect()
    }

    /// A tree of one row over the given trees.
    fn tree_with(k: &FutharkKingdom, name: &str, kids: Vec<Tree>) -> Tree {
        let symbol = k
            .rows
            .iter()
            .position(|r| r.name == name)
            .unwrap_or_else(|| panic!("the kingdom has no row {name}")) as u32;
        Tree { symbol, const_index: None, kids }
    }

    /// A leaf: a row with no children.
    fn leaf(k: &FutharkKingdom, name: &str) -> Tree {
        tree_with(k, name, Vec::new())
    }

    /// `map` with the identity row function over a matrix.
    fn map_over(k: &FutharkKingdom, class: &str, matrix: &str) -> Tree {
        tree_with(
            k,
            &format!("map_rows@{class}"),
            vec![leaf(k, "fn.arr_f32_arr_f32.id"), leaf(k, matrix)],
        )
    }

    #[test]
    fn every_row_has_a_cost() {
        let k = kingdom();
        let t = table(&k);
        for row in &k.rows {
            t.of(&row.name).unwrap_or_else(|e| panic!("{e}"));
        }
    }

    #[test]
    fn a_polynomial_is_parsed_and_evaluated() {
        let roles: Vec<String> = vec!["m".to_string(), "n".to_string()];
        let p = Poly::parse("2*n*m+n", &roles).expect("the polynomial parses");
        let sizes: BTreeMap<String, usize> = [("m".to_string(), 3usize), ("n".to_string(), 2)].into_iter().collect();
        assert_eq!(p.eval(&sizes).expect("the polynomial evaluates"), 2 * 2 * 3 + 2);
    }

    #[test]
    fn a_map_over_an_input_reads_it_and_writes_it() {
        let k = kingdom();
        let t = table(&k);
        // `map` over a 2x3 matrix: 6 elements read, 6 written.
        let tree = map_over(&k, "mat.n.m", "mat.n.m.input");
        let cost = program_cost(&tree, &k, &t).expect("the cost is computed");
        let score = score_at(&cost, &sizes()).expect("the score is computed");
        assert_eq!(score.traffic, 12, "six read and six written");
        assert_eq!(score.alloc, 6, "the result is six elements of fresh memory");
        assert_eq!(score.depth, 0, "no reduction");
    }

    #[test]
    fn a_fused_chain_costs_less_than_an_unfused_one() {
        let k = kingdom();
        let t = table(&k);
        // `map f (map g A)`: the inner map is absorbed, so the chain costs one
        // read of A and one write of the result — 6 and 6, at 2x3.
        let fused = tree_with(
            &k,
            "map_rows@mat.n.m",
            vec![
                leaf(&k, "fn.arr_f32_arr_f32.id"),
                map_over(&k, "mat.n.m", "mat.n.m.input"),
            ],
        );
        let fused_cost = program_cost(&fused, &k, &t).expect("costed");
        let fused_score = score_at(&fused_cost, &sizes()).expect("scored");
        assert_eq!(fused_score.traffic, 12, "six read and six written");
        assert_eq!(fused_score.alloc, 6, "one result, and no intermediate");

        // `transpose (map g A)`: the inner map is materialised, because
        // `transpose` is not elementwise — so the intermediate is written
        // and read again: 24 and 12.
        let unfused = tree_with(
            &k,
            "transpose@mat.m.n",
            vec![map_over(&k, "mat.n.m", "mat.n.m.input")],
        );
        let unfused_cost = program_cost(&unfused, &k, &t).expect("costed");
        let unfused_score = score_at(&unfused_cost, &sizes()).expect("scored");
        assert_eq!(unfused_score.traffic, 24, "read, written, read, written");
        assert_eq!(unfused_score.alloc, 12, "the intermediate and the result");
        assert!(
            fused_score.traffic < unfused_score.traffic,
            "the fused chain costs {} and the unfused one {}",
            fused_score.traffic,
            unfused_score.traffic
        );
    }

    /// The matmul is charged the TILED traffic: each operand read once.
    #[test]
    fn the_matmul_is_charged_the_tiled_traffic() {
        let k = kingdom();
        let t = table(&k);
        let tree = tree_with(
            &k,
            "matmul@mat.n.mxmat.m.p",
            vec![leaf(&k, "mat.n.m.input"), leaf(&k, "mat.m.p.input")],
        );
        let cost = program_cost(&tree, &k, &t).expect("the cost is computed");
        let score = score_at(&cost, &sizes()).expect("the score is computed");
        // n*m + m*p read, n*p written, with n=2, m=3, p=4.
        assert_eq!(score.traffic, 2 * 3 + 3 * 4 + 2 * 4);
        assert_eq!(score.alloc, 2 * 4);
        assert_eq!(score.depth, 3, "the reduction is three long");
    }

    /// A random gene's cost is computable — the model never panics on a
    /// program the engine can express.
    ///
    /// A random gene may express a program that is *only* the interface's
    /// input, and such a program costs nothing: the input is read, never
    /// written. So the test says that the cost is computable for every
    /// gene, and that the programs that do some work cost something.
    #[test]
    fn a_random_gene_can_be_costed() {
        let k = kingdom();
        let t = table(&k);
        let contract = k.relations().check().expect("the contract");
        let root = k.ty("mat.n.p").expect("the root class");
        let layout = GeneLayout::from_program_size(&contract, root, 3).expect("layout");
        let const_len = k.const_len();
        let mut rng: u64 = 0xC057_1E55_0001;
        let mut working = 0usize;
        for _ in 0..64 {
            let mut gene = vec![0u32; layout.width];
            for (pos, cell) in gene.iter_mut().enumerate() {
                let alphabet = layout.alphabet(&contract, pos, &const_len);
                rng = rng.wrapping_mul(6364136223846793005).wrapping_add(1442695040888963407);
                *cell = alphabet[((rng >> 33) as usize) % alphabet.len()];
            }
            let tree = express(&contract, &layout, &gene, &const_len).expect("legal").tree();
            let cost = program_cost(&tree, &k, &t).expect("the cost is computed");
            let score = score_at(&cost, &sizes()).expect("the score is computed");
            if score.traffic > 0 {
                working += 1;
            }
        }
        assert!(working > 0, "no random gene expressed a program that does any work");
    }
}
